#!/usr/bin/env python3
"""Writes worldgen/tests/data/history-report/h20-v11.toml (P5-08 16 item 11, format v11, schema 14) and its expected
lines h20-v11.expected.txt, and prints what the fixture shows.

  python3 -B worldgen/tests/reference/p5_08_h20_fixture.py [--lines]

H20 is a replayed history, not a hand-made one (reading P-R16 of p5_08_pantheon_reference: the features of 16 item 11
need a pantheon, cults, towers, the deep and alliances working together, which a hand-made fixture would have to
rebuild rule by rule): the reference's replay of the fixture cases of worldgen/tests/data/pantheon/ and pantheon-small
on the conflict stress geographies (span 2000), the run that shows the most of 16 item 11's features, dumped in the
fixture format of worldgen/tests/data/history-report/README.md with the schema 14 tables (god with six columns, faction)
and the 0.30.0 catalogue and templates. The expected file holds, one per line, `<level> <line>` for lines the v11
report must contain at that level: the [pantheon] and [cults] blocks (10 items 2, 3), every realm's `gods:` and
`faith:` lines (10 item 4), the [stats] lines of 10 item 8 (renewals_capped and deep_stirred are not in rows: the
report's values are checked only from rows, F3 of the notes), and the sentence of the first event of every kind 100 to
110 (8.2), all from the reference's rows. Written by the test writer from the spec; never from C++ output.
"""
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

import p3_engine_reference as pe  # noqa: E402
import p5_08_pantheon_reference as p508  # noqa: E402

OUT = os.path.join(pe.REPO, "worldgen", "tests", "data", "history-report", "h20-v11.toml")
EXPECTED = os.path.join(pe.REPO, "worldgen", "tests", "data", "history-report", "h20-v11.expected.txt")
FEATURES = ("bless", "curse", "champion", "monster", "sacred mark", "profane mark", "flare", "prophet founder",
            "ruler founder", "cult_spread", "cult_adopted", "hidden", "ended suppressed", "ended fell",
            "tower_taken_up", "tower_abandoned", "champion led a battle", "deep sealed", "aid")


def features(res):
    x = p508.X(res)
    seen = set(p508.paths_of(res)) - {"flare"}   # a flare by a god: a flare-up phase whose first-year act cites it
    champs = {f[0] for f in res.get("figure", []) if f[3] == p508.CHAMPION}
    for e in x.of("battle_led"):
        if any(p[3] in champs and p[2] == p508.FIGURE for p in x.r.parts.get(e, [])):
            seen.add("champion led a battle")
    if x.of("deep_sealed") or x.of("warren_sealed"):
        seen.add("deep sealed")
    if x.of("ally_aided_hold"):
        seen.add("aid")
    if p508.flares_of(x):
        seen.add("flare")
    return {f for f in FEATURES if f in seen}


def candidates(quick=False):
    pcr = p508._pcr()
    pcr.use_version(p508.VERSION)
    out = []
    for name in p508.fixture_files():
        d, cases, _paths, _doc = p508.fixture_data(name)
        for seed, case, activity in cases:
            if case[0] != 2000:
                continue
            res, inp = p508.run_case(seed, d, case, activity)
            out.append(("%s seed %d" % (name, seed), res, inp))
    dat = p508.pantheon_small_data()
    for seed in (0, 2, 4, 6, 12, 14):
        case = pcr.STRESS_CASES.get(seed, pcr.synthetic_case(seed))
        if case[0] != 2000:
            continue
        res, inp = p508.run_case(seed, dat, case)
        out.append(("pantheon-small stress-%d" % seed, res, inp))
        if quick:
            break
    return out


def tv(v):
    if v is None:
        return "-1"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(tv(x) for x in v) + "]"
    raise TypeError(v)


def rows(name, rs):
    if not rs:
        return "%s = []\n" % name
    return "%s = [\n" % name + "".join("    %s,\n" % tv(list(r)) for r in rs) + "]\n"


def dump(label, res, inp):
    w = res["_world"]
    cat = {k[0]: k for k in res["event_kind"]}
    roles = {}
    for k, seq, role, typ, lo, hi in res["event_kind_role"]:
        roles.setdefault(k, []).append((seq, role, typ, lo, hi))
    values = {}
    for k, seq, key in res["event_kind_value"]:
        values.setdefault(k, []).append((seq, key))
    o = ["# P5-08 16 item 11: H20 (format v11, schema 14). Generated by p5_08_h20_fixture.py from the reference's replay",
         "# (%s, span %d); the 0.30.0 catalogue and templates (8.1, 8.2). Shows: %s." % (
             label, inp.params["span"], ", ".join(sorted(features(res)))),
         "# Written by the test writer from the spec; format: README.md (schema 14: god rows have six columns, faction",
         "# rows thirteen; -1 is NULL in every nullable column).",
         "[meta]", "seed = %d" % inp.seed, 'seed_phrase = ""', "map_size = %d" % inp.map_size,
         "history_span = %d" % inp.params["span"], 'history_detail = "normal"',
         'races = "%s"' % ",".join(r[1] for r in inp.races if r[9] == 1), 'civs_per_race = "auto"',
         'event_intensity = "normal"', 'monster_pressure = "normal"', 'divine_activity = "normal"', 'divine_script = ""',
         "", "[tables]"]
    o.append(rows("biome", [(1, "grassland", "Grassland", 8421376, 0)]).rstrip("\n"))
    o.append(rows("region", [(r["id"], r["name"], 1, r["cells"], r.get("lake_cells", 0), r["walk_cells"])
                             for r in inp.regions]).rstrip("\n"))
    o.append(rows("race", inp.races).rstrip("\n"))
    o.append(rows("culture", inp.cultures).rstrip("\n"))
    o.append(rows("god", res["god"]).rstrip("\n"))
    o.append(rows("age", inp.ages).rstrip("\n"))
    o.append(rows("phase", res["phase"]).rstrip("\n"))
    o.append(rows("civilization", res["civilization"]).rstrip("\n"))
    o.append(rows("settlement", [s[:14] for s in res["settlement"]]).rstrip("\n"))
    for t in ("settlement_census", "region_control", "relation", "region_name", "beast", "monster_kind",
              "beast_population", "monster", "site", "race_relation", "settlement_race", "figure", "book", "faction"):
        o.append(rows(t, res.get(t, [])).rstrip("\n"))
    for kid in sorted(cat):
        k = cat[kid]
        o += ["", "[[kind]]", "key = %s" % tv(k[1]), "caused = %d" % k[2], "region_use = %d" % k[3],
              "settlement_use = %d" % k[4], "salience = %d" % k[5], "template = %s" % tv(k[6]),
              "roles = %s" % tv([[r[1], r[2], r[3], r[4]] for r in sorted(roles.get(kid, []))]),
              "values = %s" % tv([v[1] for v in sorted(values.get(kid, []))])]
    parts = {}
    for p in res["event_participant"]:
        parts.setdefault(p[0], []).append(p)
    causes = {}
    for e, c in res["event_cause"]:
        causes.setdefault(e, []).append(c)
    vals = {}
    for e, seq, v in res["event_value"]:
        vals.setdefault(e, []).append((seq, v))
    for e in res["event"]:
        eid, year, end, kind, phase, region, settlement, salience = e
        rs = {r[0]: r[1] for r in roles.get(kind, [])}
        o += ["", "[[event]]", "id = %d" % eid, "year = %d" % year]
        if end != year:
            o.append("end = %d" % end)
        o += ["kind = %s" % tv(cat[kind][1]), "phase = %d" % phase]
        if region:
            o.append("region = %d" % region)
        if settlement:
            o.append("settlement = %d" % settlement)
        if salience != cat[kind][5]:
            o.append("salience = %d" % salience)
        ps = sorted(parts.get(eid, []), key=lambda p: p[1])
        if ps:
            o.append("parts = %s" % tv([[rs[p[2]], p[4]] for p in ps]))
        if vals.get(eid):
            o.append("values = %s" % tv([v for _s, v in sorted(vals[eid])]))
        if causes.get(eid):
            o.append("causes = %s" % tv(sorted(causes[eid])))
    return "\n".join(o) + "\n"


def expected(res, inp):
    w = res["_world"]
    lines = []
    for level in ("full", "summary"):
        lines += ["%s %s" % (level, ln) for ln in p508.pantheon_block(res, level)]
        lines += ["%s %s" % (level, ln) for ln in p508.cults_block(res, level)]
    for c in res["civilization"]:
        for ln in p508.realm_lines(res, c[0]):
            lines.append("full %s" % ln)
    for k, v in p508.stats_of_tables(res):
        if k not in ("renewals_capped", "deep_stirred"):
            lines.append("full %s = %d" % (k, v))
    view = pe.view_from_rows(res, [(r["id"], r["name"]) for r in inp.regions], inp.races, inp.gods)
    x = p508.X(res)
    for kid in sorted(p508.KINDS):
        es = x.of(p508.KINDS[kid])
        if es:
            lines.append("full sentence %s" % pe.render(view, es[0]))
    del w
    return lines


def main(argv):
    quick = "--quick" in argv
    cands = candidates(quick)
    best = max(cands, key=lambda c: (len(features(c[1])), -len(c[1]["event"])))
    label, res, inp = best
    for lab, r, _i in cands:
        print("%-40s events %5d features %2d: %s" % (lab, len(r["event"]), len(features(r)),
                                                     ", ".join(sorted(set(FEATURES) - features(r)))))
    print("chosen: %s (missing: %s)" % (label, ", ".join(sorted(set(FEATURES) - features(res))) or "none"))
    with open(OUT, "w", newline="\n") as f:
        f.write(dump(label, res, inp))
    lines = expected(res, inp)
    with open(EXPECTED, "w", newline="\n") as f:
        f.write("# P5-08 16 item 11: lines the v11 report of H20 (h20-v11.toml) must contain, `<level> <line>`; written\n"
                "# by worldgen/tests/reference/p5_08_h20_fixture.py from the reference's rows (never from C++ output).\n")
        f.write("\n".join(lines) + "\n")
    if "--lines" in argv:
        print("\n".join(lines))
    print("wrote %s (%d events) and %s (%d lines)" % (OUT, len(res["event"]), EXPECTED, len(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
