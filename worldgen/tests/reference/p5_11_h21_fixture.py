#!/usr/bin/env python3
"""Writes worldgen/tests/data/history-report/h21-v12.toml (P5-11 16 item 10, format v12, schema 15) and its expected
lines h21-v12.expected.txt, and prints what the fixture shows.

  python3 -B worldgen/tests/reference/p5_11_h21_fixture.py [--quick] [--lines]

H21 is made from H20 by this script: H20's shape (p5_08_h20_fixture.dump: a replayed history of the reference on a
conflict stress geography at span 2000, `Synthetic <n>` names lettered) with the 0.31.0 rules, the artifacts-small
tuning (spec 4.6) and the fixture files of worldgen/tests/data/artifacts/, and the three schema 15 tables
(artifact_kind, artifact, artifact_holding) added to its [tables]. The candidate run that shows the most of 16 item
10's features is chosen; the features it lacks are printed (and named in docs/reviews/p5-11-tests-notes.md).

The expected file holds, one per line, `<level> <line>` for lines the v12 report must contain at that level (the
[artifacts] block at both levels, every realm's `artifacts:` line at full, the [stats] lines of 10 item 6 that rows
give, and `sentence <text>` for the first event of every kind 111 to 116), and `part-full <needle>\\t<fragment>` for a
full-level line that must contain both (the [figures] lines' `; bore ...` and `; made ...`, the [monsters] lines'
`, hoard ...`), all from the reference's rows. Written by the test writer from the spec; never from C++ output.
"""
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

import p3_engine_reference as pe  # noqa: E402
import p5_08_h20_fixture as h20  # noqa: E402
import p5_11_artifacts_reference as p511  # noqa: E402

OUT = os.path.join(pe.REPO, "worldgen", "tests", "data", "history-report", "h21-v12.toml")
EXPECTED = os.path.join(pe.REPO, "worldgen", "tests", "data", "history-report", "h21-v12.expected.txt")
FEATURES = ("maker 1", "maker 2", "maker 3", "maker 4", "deep", "claim cited", "M1", "M2", "M3", "M4", "M5", "M6",
            "M7", "M8", "M9", "M10", "M11", "M12", "M13", "M14")
MOVE_ROW = {"general_appointed": "M1", "figure_died": "M2", "fell_in_battle": "M3", "hero_slain": "M4",
            "monster_slain_by_hero": "M5", "monster_slain": "M5", "monster_died": "M6", "monster_raid": "M7",
            "hold_lost": "M8", "sacked": "M9", "settlement_captured": "M10", "civ_conquered": "M11", "civ_ended": "M12",
            "peace": "M13", "war_won": "M13", "cult_suppressed": "M14"}


def features(res):
    seen = set()
    for p in p511.paths_of(res):
        if p.startswith("maker ") or p in ("deep", "claim cited"):
            seen.add(p)
        if p.startswith("move "):
            seen.add(MOVE_ROW.get(p.split()[1], "?"))
    return {f for f in FEATURES if f in seen}


def candidates(quick=False):
    pcr = p511._pcr()
    pcr.use_version(p511.VERSION)
    out = []
    for name in p511.fixture_files():
        d, cases, _paths, _doc = p511.fixture_data(name)
        for seed, case in cases:
            if case[0] != 2000:
                continue
            res, inp = p511.run_case(seed, d, case)
            out.append(("%s seed %d" % (name, seed), res, inp))
    dat = p511.artifacts_small_data()
    for seed in (0, 2, 6, 12, 14):
        case = pcr.STRESS_CASES.get(seed, pcr.synthetic_case(seed))
        if case[0] != 2000:
            continue
        res, inp = p511.run_case(seed, dat, case)
        out.append(("artifacts-small stress-%d" % seed, res, inp))
        if quick:
            break
    return out


def dump(label, res, inp):
    text = h20.dump(label, res, inp)
    text = text.replace("# P5-08 16 item 11: H20 (format v11, schema 14). Generated by p5_08_h20_fixture.py from the "
                        "reference's replay",
                        "# P5-11 16 item 10: H21 (format v12, schema 15). Generated by p5_11_h21_fixture.py from the "
                        "reference's replay")
    extra = "".join(h20.rows(t, res.get(t, [])) for t in ("artifact_kind", "artifact", "artifact_holding"))
    i = text.index("\n\n[[kind]]")
    return text[:i] + "\n" + extra.rstrip("\n") + text[i:]


def expected(res, inp):
    lines = []
    for level in ("full", "summary"):
        lines += ["%s %s" % (level, ln) for ln in p511.artifacts_block(res, level)]
    for c in res["civilization"]:
        ln = p511.realm_line(res, c[0])
        if ln is not None:
            lines.append("full %s" % ln)
    r = p511.R(res)
    for f, frag in sorted(p511.figure_fragments(res).items()):
        lines.append("part-full f%d %s\t%s" % (f, r.fig_name(f), frag))
    for m, frag in sorted(p511.monster_fragments(res).items()):
        lines.append("part-full m%d %s\t%s" % (m, r.mon[m][1], frag))
    for k, v in p511.stats_of_tables(res):
        if k not in p511.REPLAY_STATS:
            lines.append("full %s = %d" % (k, v))
    view = pe.view_from_rows(res, [(x["id"], x["name"]) for x in inp.regions], inp.races, inp.gods)
    for kid in sorted(p511.KINDS):
        es = r.of(p511.KINDS[kid])
        if es:
            lines.append("full sentence %s" % pe.render(view, es[0]))
    return lines


def main(argv):
    quick = "--quick" in argv
    cands = candidates(quick)
    best = max(cands, key=lambda c: (len(features(c[1])), -len(c[1]["event"])))
    label, res, inp = best
    res, inp = h20.lettered(res, inp)
    res["_end"] = inp.params["span"] - 1
    res["region"] = [(x["id"], x["name"]) for x in inp.regions]
    for lab, rr, _i in cands:
        print("%-40s events %5d features %2d: missing %s" % (lab, len(rr["event"]), len(features(rr)),
                                                            ", ".join(f for f in FEATURES if f not in features(rr))))
    print("chosen: %s (missing: %s)" % (label, ", ".join(f for f in FEATURES if f not in features(res)) or "none"))
    with open(OUT, "w", newline="\n") as f:
        f.write(dump(label, res, inp))
    lines = expected(res, inp)
    with open(EXPECTED, "w", newline="\n") as f:
        f.write("# P5-11 16 item 10: lines the v12 report of H21 (h21-v12.toml) must contain, `<level> <line>` or\n"
                "# `part-full <needle>\\t<fragment>`; written by worldgen/tests/reference/p5_11_h21_fixture.py from the\n"
                "# reference's rows (never from C++ output).\n")
        f.write("\n".join(lines) + "\n")
    if "--lines" in argv:
        print("\n".join(lines))
    print("wrote %s (%d events) and %s (%d lines)" % (OUT, len(res["event"]), EXPECTED, len(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
