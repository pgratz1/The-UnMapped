_GLYPHS = {}


def cached_glyph(key):
    if key not in _GLYPHS:
        _GLYPHS[key] = glyph(*key)
    return _GLYPHS[key]


def draw_list(m, colours):
    """[(x, y, glyph key, fill colour or None)] in the order of 6.1."""
    out = []
    for _pid, x, y, _kind in m["passes"]:
        out.append((x, y, (10, False, False), None))
    for x, y, sym, _evs in m["places"]:
        out.append((x, y, (11, False, False), SYMBOL_COLOUR[sym]))
    ss = m["settlements"]

    def fill(s):
        return colours[s["owner"] - 1] if s["owner"] else NO_OWNER
    out += [(s["x"], s["y"], (9, False, False), FADED) for s in ss if s["type"] == "faded"]
    out += [(s["x"], s["y"], (8, False, False), None) for s in ss if s["type"] == "ruin"]
    out += [(s["x"], s["y"], glyph_of(s), fill(s)) for s in ss if s["type"] == "standing" and not s["capital"]]
    out += [(s["x"], s["y"], glyph_of(s), fill(s)) for s in ss if s["type"] == "standing" and s["capital"]]
    return out


def draw(buf, w, h, k, m, colours):
    """Draws the markers onto buf (bytearray, RGB, w k by h k pixels) in place (6.2)."""
    assert len(buf) == 3 * w * k * h * k and 1 <= k <= 16
    W = w * k
    for x, y, key, col in draw_list(m, colours):
        radius, cells = cached_glyph(key)
        n = 2 * radius + 1
        for dy in range(-radius, radius + 1):
            cy = y + dy
            if not 0 <= cy < h:
                continue
            for dx in range(-radius, radius + 1):
                cx = x + dx
                if not 0 <= cx < w:
                    continue
                c = cells[(dy + radius) * n + dx + radius]
                if c == 1:
                    rgb = HALO
                elif c == 2:
                    rgb = col
                    assert rgb is not None, "glyph %r has a fill cell but no fill colour" % (key,)
                elif c == 3:
                    rgb = INK
                else:
                    continue
                px = bytes(rgb) * k
                for j in range(k):
                    o = 3 * ((cy * k + j) * W + cx * k)
                    buf[o:o + 3 * k] = px
    return buf


def upscale(img, w, h, k):
    out = bytearray()
    for y in range(h):
        row = img[3 * w * y:3 * w * (y + 1)]
        line = b"".join(row[3 * x:3 * x + 3] * k for x in range(w))
        out += line * k
    return bytes(out)


def overlay(w, base, colours, y, k=1, faded=True):
    img = bytearray(base.render(tl.territory_fill(w.h, colours, y), tl.territory_holders(w.h, y), scale=k))
    draw(img, base.w, base.h, k, w.markers(y, faded=faded), colours)
    return bytes(img)


