def check_draw_order(c):
    """10.2 item 4 on a 32 x 24 canvas: a ring, a ruin and two settlements overlapping; clipping."""
    w_, h_ = 32, 24
    colours = [(10, 20, 30), (40, 50, 60)]
    bg = (7, 77, 177)
    m = {"year": 0, "passes": [(1, 30, 1, 1)], "places": [(10, 10, SACK, [5])],
         "settlements": [
             {"settlement": 1, "x": 10, "y": 10, "type": "standing", "kind": 2, "status": 1, "owner": 1,
              "capital": True},
             {"settlement": 2, "x": 17, "y": 10, "type": "standing", "kind": 3, "status": 2, "owner": 2,
              "capital": False},
             {"settlement": 3, "x": 3, "y": 16, "type": "ruin", "kind": 1, "status": 3, "owner": 0, "capital": False},
             {"settlement": 4, "x": 0, "y": 23, "type": "standing", "kind": 1, "status": 1, "owner": 0,
              "capital": False}]}
    img = draw(bytearray(bytes(bg) * (w_ * h_)), w_, h_, 1, m, colours)

    def px(x, y, im=img, ww=w_):
        i = 3 * (y * ww + x)
        return tuple(im[i:i + 3])
    want = {(10, 10): colours[0],   # capital village centre
            (13, 10): INK,          # capital ink over the town's halo (capitals last)
            (15, 10): HALO,         # capital halo over the town's fill
            (16, 10): bg,           # declining town interior over the ring's inside: the canvas
            (17, 10): HALO,         # declining town interior shows the ring's inner halo (halo rule inside C(7))
            (18, 10): INK,          # declining town interior shows the ring's ink below
            (19, 10): colours[1],   # town fill over the ring's colour band
            (20, 10): INK, (21, 10): HALO,
            (10, 1): (200, 0, 200),  # ring band (dy = -9), not covered
            (3, 16): INK,           # ruin over the ring's band
            (4, 16): HALO,          # ruin halo over the ring's ink
            (0, 23): NO_OWNER,      # hamlet without owner, clipped at two edges
            (30, 0): INK, (31, 1): INK, (31, 0): HALO,   # pass clipped at the top and right edges
            (0, 0): bg}
    for (x, y), rgb in want.items():
        c.eq("6.1 pixel (%d, %d)" % (x, y), px(x, y), rgb)
    # every pixel changed is one of the marker colours
    allowed = {INK, HALO, NO_OWNER, (200, 0, 200)} | set(colours)
    c.eq("12 inv 9 colours", {px(x, y) for y in range(h_) for x in range(w_)} - allowed - {bg}, set())
    # scale 3 equals scale 1 scaled
    img3 = draw(bytearray(bytes(bg) * (w_ * h_ * 9)), w_, h_, 3, m, colours)
    c.eq("6.2 scale 3 = scale 1 scaled", bytes(img3), upscale(bytes(img), w_, h_, 3))


def check_invariants(c, name, w, every_year=True, report=None, generated=False):
    E = w.E
    years = range(E + 1) if every_year else golden_years(w)
    seen = set()
    became_faded = {}
    for e in w.h.events:
        if w.kind_key[e[3]] == b"ruin_faded" and e[6] and e[6] not in became_faded:
            became_faded[e[6]] = e[1]
    for y in years:
        m = w.markers(y)
        ids = [s["settlement"] for s in m["settlements"]]
        c.count += 1
        want = [s[0] for s in w.h.settlements if s[6] <= y]
        if ids != want:
            c.eq("%s inv 1 at %d" % (name, y), ids, want)
        if not seen.issubset(set(ids)):
            c.eq("%s inv 1 stays at %d" % (name, y), sorted(seen - set(ids)), [])
        seen = set(ids)
        for s in m["settlements"]:
            sid = s["settlement"]
            R = w.R[sid]
            if R == -1 and s["type"] in ("ruin", "faded"):
                continue   # M9: a hand-made ruin without a status-3 census row (h11-v2 s11); 3.3 gives -1
            if R != -1 and y >= R:
                f = became_faded.get(sid)
                want_t = "faded" if f is not None and y >= f else "ruin"
                if s["type"] != want_t:
                    c.eq("%s inv 3 s%d at %d" % (name, sid, y), s["type"], want_t)
            elif s["type"] != "standing":
                c.eq("%s inv 3 s%d at %d (before ruin)" % (name, sid, y), s["type"], "standing")
        if generated:
            alive = w.alive(y)
            caps = {}
            for s in m["settlements"]:
                if s["capital"]:
                    if s["type"] != "standing" or s["owner"] not in alive:
                        c.eq("%s inv 4 capital s%d at %d" % (name, s["settlement"], y), False, True)
                    caps.setdefault(s["owner"], []).append(s["settlement"])
            for civ in sorted(alive):
                c.count += 1
                if len(caps.get(civ, [])) != 1:
                    c.eq("%s inv 4 civ %d at %d" % (name, civ, y), caps.get(civ, []), ["one"])
        # inv 6
        evs = [e for e in w.h.events_of(y) if w.ev[e][5] or w.ev[e][6]]
        got = sorted(e for p in m["places"] for e in p[3])
        if got != evs:
            c.eq("%s inv 6 at %d" % (name, y), got, evs)
        firsts = [p[3][0] for p in m["places"]]
        if firsts != sorted(firsts):
            c.eq("%s inv 6 order at %d" % (name, y), firsts, sorted(firsts))
        for p in m["places"]:
            if p[2] != max(event_symbol(w.kind_key[w.ev[e][3]]) for e in p[3]):
                c.eq("%s inv 6 symbol at %d" % (name, y), p[2], None)
    # inv 2
    end = w.markers(E)
    c.eq("%s inv 2" % name, [(s["settlement"], s["owner"], s["kind"], s["status"], s["population"])
                             for s in end["settlements"]],
         [(s[0], s[8], s[9], s[10], s[11]) for s in w.h.settlements])
    # inv 4 at E against civilization.capital, inv 5
    if generated:
        for civ in w.h.civs:
            if civ[8] is None:
                c.eq("%s inv 4 at E c%d" % (name, civ[0]), w.capital(civ[0], E), civ[5])
    for s in w.h.settlements:
        if s[10] == 3:
            c.eq("%s inv 5 R(s%d)" % (name, s[0]), w.R[s[0]], s[12])
        if s[10] == 4 and generated:
            ev = w.ruin_ev[s[0]]
            c.eq("%s inv 5 faded s%d event year" % (name, s[0]), w.ev[ev][1] if ev else None, w.R[s[0]])
    if report is not None:
        check_present(c, name, w, end, report)


def check_present(c, name, w, end, text):
    """9.2 M2 on the report's [present] and [civilizations] blocks: entries at E with faded on."""
    lines = text.split("\n")
    i = lines.index("[present]")
    pres = []
    for ln in lines[i + 1:]:
        if ln.startswith("["):
            break
        pres.append(ln)
    want = []
    kind_of = {v: k for k, v in KIND_WORD.items()}
    status_of = {v: k for k, v in STATUS_WORD.items()}
    for ln in pres:
        if ln.startswith("  s") and ": " in ln and ", population " in ln:
            head, rest = ln[3:].split(" ", 1)
            sid = int(head)
            body = rest.split(": ", 1)[1].split(", ")
            if len(body) < 4 or body[0] not in kind_of or body[1] not in status_of:
                continue   # the refuge and ruin lists of [present] (24.7), not settlement lines
            kind, status = kind_of[body[0]], status_of[body[1]]
            pop = int(body[2].split(" ")[1])
            owner = 0 if body[3] == "no owner" else int(body[3].rsplit("(c", 1)[1].rstrip(")"))
            at = [b for b in body if b.startswith("at ")][0].split(" ")
            want.append((sid, kind, status, pop, owner, int(at[1]), int(at[2])))
    got = [(s["settlement"], s["kind"], s["status"], s["population"], s["owner"], s["x"], s["y"])
           for s in end["settlements"]]
    c.eq("%s [present] settlement lines" % name, got, want)
    cnt = [ln for ln in pres if ln.startswith("settlements: ")][0]
    by = {st: sum(1 for s in end["settlements"] if s["status"] == st) for st in (1, 2, 3, 4)}
    c.eq("%s [present] counts" % name, cnt, "settlements: %d; thriving %d, declining %d, ruined %d, faded %d" % (
        len(end["settlements"]), by[1], by[2], by[3], by[4]))
    kc = [ln for ln in pres if ln.startswith("settlement kinds: ")][0]
    kk = {k: sum(1 for s in end["settlements"] if s["kind"] == k) for k in range(1, 6)}
    c.eq("%s [present] kinds" % name, kc, "settlement kinds: hamlet %d, village %d, town %d, city %d, fortress %d"
         % tuple(kk[k] for k in range(1, 6)))
    caps = sorted(int(ln.rsplit("(s", 1)[1].rstrip(")")) for ln in lines if ln.startswith("  capital: ") and "(s" in ln)
    c.eq("%s [civilizations] capitals" % name, sorted(s["settlement"] for s in end["settlements"] if s["capital"]),
         caps)


