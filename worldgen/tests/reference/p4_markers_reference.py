def disc(r, dx, dy):
    return dx * dx + dy * dy <= r * r + r


def square(r, dx, dy):
    return max(abs(dx), abs(dy)) <= r


def diamond(r, dx, dy):
    return abs(dx) + abs(dy) <= r


SHAPE = {1: (disc, 1), 2: (disc, 2), 3: (square, 2), 4: (square, 3), 5: (diamond, 3)}


def halo(radius, cells):
    n = 2 * radius + 1
    out = list(cells)
    for j in range(n):
        for i in range(n):
            if cells[j * n + i] != 0:
                continue
            for b in (-1, 0, 1):
                for a in (-1, 0, 1):
                    if (a or b) and 0 <= i + a < n and 0 <= j + b < n and cells[(j + b) * n + i + a] == 3:
                        out[j * n + i] = 1
    return out


def glyph(base, declining=False, capital=False):
    """(radius, cells) of section 5; ValueError for a key it does not define."""
    if base in SHAPE:
        P, r = SHAPE[base]
        o = r + 1 + (1 if capital else 0)
        radius = o + 1
        n = 2 * radius + 1
        cells = [0] * (n * n)
        for dy in range(-radius, radius + 1):
            for dx in range(-radius, radius + 1):
                i = (dy + radius) * n + dx + radius
                if P(r, dx, dy):
                    cells[i] = 4 if declining and P(r - 1, dx, dy) else 2
                elif P(o, dx, dy):
                    cells[i] = 3
                if base == 4 and square(1, dx, dy):
                    cells[i] = 3
        return radius, halo(radius, cells)
    if declining or capital:
        raise ValueError("glyph: base %d with declining or capital" % base)
    if base in (8, 9, 10):
        radius = 2 if base == 9 else 3
        n = 2 * radius + 1
        cells = [0] * (n * n)
        for dy in range(-radius, radius + 1):
            for dx in range(-radius, radius + 1):
                i = (dy + radius) * n + dx + radius
                if base in (8, 9) and abs(dx) == abs(dy) <= 2:
                    cells[i] = 3 if base == 8 else 2
                if base == 10 and abs(dx) <= 2 and dy == abs(dx) - 1:
                    cells[i] = 3
        return radius, (cells if base == 9 else halo(radius, cells))
    if base == 11:
        radius = 11
        n = 2 * radius + 1
        cells = [0] * (n * n)
        for dy in range(-radius, radius + 1):
            for dx in range(-radius, radius + 1):
                i = (dy + radius) * n + dx + radius
                if (disc(10, dx, dy) and not disc(9, dx, dy)) or (disc(8, dx, dy) and not disc(7, dx, dy)):
                    cells[i] = 3
                elif disc(9, dx, dy) and not disc(8, dx, dy):
                    cells[i] = 2
        return radius, halo(radius, cells)
    raise ValueError("glyph: base %d" % base)


def glyph_name(base, declining=False, capital=False):
    if base in KIND_WORD:
        return KIND_WORD[base] + (" declining" if declining else "") + (" capital" if capital else "")
    return {8: "ruin", 9: "faded", 10: "pass", 11: "ring"}[base]


def glyph_keys():
    keys = [(b, d, c) for b in range(1, 6) for d in (False, True) for c in (False, True)]
    return keys + [(8, False, False), (9, False, False), (10, False, False), (11, False, False)]


def glyph_dump():
    out = []
    for key in glyph_keys():
        radius, cells = glyph(*key)
        n = 2 * radius + 1
        out.append("glyph %s %d" % (glyph_name(*key), radius))
        for j in range(n):
            out.append("".join(str(v) for v in cells[j * n:(j + 1) * n]))
    return ("\n".join(out) + "\n").encode("ascii")


def glyph_of(entry):
    if entry["type"] == "ruin":
        return (8, False, False)
    if entry["type"] == "faded":
        return (9, False, False)
    return (entry["kind"], entry["status"] == 2, entry["capital"])


