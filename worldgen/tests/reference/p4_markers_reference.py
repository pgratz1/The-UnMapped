class World:
    """The history of a world (P4-01's rows) plus the region seed cells, the pass rows and the catalogue."""

    def __init__(self, path):
        self.path = path
        self.h = tl.History(path)
        h = self.h
        self.E = h.E
        conn = prr.connect(path)
        try:
            cols, rows = prr.pk_rows(conn, "region")
            ix, iy = cols.index("seed_x"), cols.index("seed_y")
            self.seed = {r[0]: (r[ix], r[iy]) for r in rows}
            cols, rows = prr.pk_rows(conn, "pass")
            self.passes = [(r[0], r[cols.index("col_x")], r[cols.index("col_y")], r[cols.index("kind")]) for r in rows]
            self.kind_key = {r[0]: r[1].encode("latin-1") for r in prr.pk_rows(conn, "event_kind")[1]}
            roles = prr.pk_rows(conn, "event_kind_role")[1]   # kind, seq, role, entity_type, min, max
        finally:
            conn.close()
        self.role_name = {(r[0], r[1]): r[2].encode("latin-1") for r in roles}
        self.ev = {e[0]: e for e in h.events}   # id, year, end_year, kind, phase, region, settlement, salience
        self.srow = {s[0]: s for s in h.settlements}
        # census years per settlement, for the state at Y (the row of largest year <= Y)
        self.cyears = {s: [c[1] for c in rows] for s, rows in h.census.items()}
        # 3.2 capital runs
        self.runs = {c[0]: [] for c in h.civs}
        for e in h.events:
            key = self.kind_key[e[3]]
            want = CAPITAL_KINDS.get(key)
            if want is None or e[6] == 0:
                continue
            named = []
            for p in h.parts.get(e[0], []):   # event, seq, role, entity_type, entity_id
                if p[3] == CIV and self.role_name.get((e[3], p[2])) == want and p[4] not in named:
                    named.append(p[4])
            for c in named:
                self.runs[c].append((e[1], e[0], e[6]))
        self.run_years = {c: [r[0] for r in run] for c, run in self.runs.items()}
        # 3.3 ruined year and ruin event
        self.R = {}
        self.ruin_ev = {}
        faded_by = {}
        for e in h.events:
            if self.kind_key[e[3]] == b"ruin_faded" and e[6] != 0 and e[6] not in faded_by:
                faded_by[e[6]] = e[0]
        for s in h.settlements:
            sid = s[0]
            r = None
            for c in h.census.get(sid, []):
                if c[4] == 3:
                    r = c[1]
                    break
            self.R[sid] = -1 if r is None else r
            if s[13]:
                self.ruin_ev[sid] = s[13]
            elif sid in faded_by:
                cs = h.causes.get(faded_by[sid], [])
                self.ruin_ev[sid] = min(cs) if cs else 0
            else:
                self.ruin_ev[sid] = 0
        self.alive_cache = {}

    def state(self, s, y):
        """P4-01 4: (exists, owner, kind, status, population, since)."""
        row = self.srow[s]
        if row[6] > y:
            return (False, 0, 0, 0, 0, 0)
        cs = self.h.census[s]
        i = bisect.bisect_right(self.cyears[s], y) - 1
        assert i >= 0, "settlement %d has no census row at or before %d" % (s, y)
        c = cs[i]
        return (True, c[2], c[3], c[4], c[5], c[1])

    def alive(self, y):
        return set(self.h.alive(y))

    def capital(self, c, y, alive=None):
        """3.2 capital(c, Y): 0 for none."""
        if alive is None:
            alive = self.alive(y)
        if c not in alive:
            return 0
        i = bisect.bisect_right(self.run_years[c], y) - 1
        if i < 0:
            return 0
        s = self.runs[c][i][2]
        ex, owner, _, status, _, _ = self.state(s, y)
        return s if ex and status in (1, 2) and owner == c else 0

    def settlement_entries(self, y, faded=True):
        """3.1: dicts in ascending settlement id."""
        alive = self.alive(y)
        out = []
        for s in self.h.settlements:
            sid = s[0]
            ex, owner, kind, status, pop, since = self.state(sid, y)
            if not ex:
                continue
            if status == 4 and not faded:
                continue
            typ = {1: "standing", 2: "standing", 3: "ruin", 4: "faded"}[status]
            cap = typ == "standing" and self.capital(owner, y, alive) == sid if owner else False
            standing = typ == "standing"
            out.append({"settlement": sid, "x": s[2], "y": s[3], "type": typ, "kind": kind, "status": status,
                        "owner": owner, "population": pop, "since": since, "founded": s[6], "capital": cap,
                        "ruined_year": -1 if standing else self.R[sid],
                        "ruin_event": 0 if standing else self.ruin_ev[sid]})
        return out

    def places(self, y):
        """3.4: (x, y, symbol, [event ids]) in ascending smallest event id."""
        out = []
        index = {}
        for eid in self.h.events_of(y):
            e = self.ev[eid]
            if e[6] != 0:
                cell = (self.srow[e[6]][2], self.srow[e[6]][3])
            elif e[5] != 0:
                cell = self.seed[e[5]]
            else:
                continue
            sym = event_symbol(self.kind_key[e[3]])
            if cell in index:
                p = out[index[cell]]
                p[3].append(eid)
                p[2] = max(p[2], sym)
            else:
                index[cell] = len(out)
                out.append([cell[0], cell[1], sym, [eid]])
        return [tuple(p) for p in out]

    def markers(self, y, faded=True, events=True, passes=True):
        if not 0 <= y <= self.E:
            raise ValueError("year %d outside 0 to %d" % (y, self.E))
        return {"year": y, "settlements": self.settlement_entries(y, faded),
                "places": self.places(y) if events else [], "passes": list(self.passes) if passes else []}


def marker_dump(m):
    out = ["year %d" % m["year"]]
    for s in m["settlements"]:
        out.append("settlement %d %d %d %s %d %d %d %d %d %d %d %d %d" % (
            s["settlement"], s["x"], s["y"], s["type"], s["kind"], s["status"], s["owner"], s["population"],
            s["since"], s["founded"], 1 if s["capital"] else 0, s["ruined_year"], s["ruin_event"]))
    for x, y, sym, evs in m["places"]:
        out.append("place %d %d %s %s" % (x, y, SYMBOL_WORD[sym], " ".join(str(e) for e in evs)))
    for pid, x, y, kind in m["passes"]:
        out.append("pass %d %d %d %d" % (pid, x, y, kind))
    return ("\n".join(out) + "\n").encode("ascii")


def static_dump(w):
    out = []
    for c in w.h.civs:
        for year, eid, s in w.runs[c[0]]:
            out.append("capital %d %d %d %d" % (c[0], year, eid, s))
    for s in w.h.settlements:
        if w.R[s[0]] != -1:
            out.append("ruin %d %d %d" % (s[0], w.R[s[0]], w.ruin_ev[s[0]]))
    return ("\n".join(out) + "\n").encode("ascii") if out else b""


