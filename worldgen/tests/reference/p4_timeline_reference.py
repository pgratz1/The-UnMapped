class Checker:
    def __init__(self):
        self.failures = 0
        self.count = 0

    def eq(self, what, got, want):
        self.count += 1
        if got != want:
            self.failures += 1
            print("FAIL %s:\n  got  %r\n  want %r" % (what, got, want))


