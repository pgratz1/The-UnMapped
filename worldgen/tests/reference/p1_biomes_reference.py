class Checker:
    def __init__(self):
        self.passes = 0
        self.fails = 0

    def eq(self, label, got, want):
        if got == want:
            self.passes += 1
        else:
            self.fails += 1
            sys.stderr.write("FAIL %s:\n  got  %r\n  want %r\n" % (label, got, want))

    def ok(self, label, cond):
        self.eq(label, bool(cond), True)


def expect_fatal(c, label, fn, prefix=None):
    try:
        fn()
    except FatalError as ex:
        c.ok(label + " message " + str(ex), prefix is None or str(ex).startswith(prefix))
        return
    c.ok(label + " is fatal", False)


