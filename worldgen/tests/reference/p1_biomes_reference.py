def rain_scale(t, n):
    """B4's size rule."""
    if n <= 512:
        return t["rain_scale_512"]
    if n <= 1024:
        return t["rain_scale_1024"]
    return t["rain_scale_2048"]


def rb(sc, b):
    """A non-sentinel rainfall bound scaled (B4); sentinels are skipped by
    rule_failures and never scaled."""
    return er.from_int(b) if b in (0, 10000) else er.mul_int(sc, b)


def jitter(temp, rain, nt, nr, t):
    """B3: (tq, rq) raw."""
    tq = er.add(er.from_ratio(temp, 10), er.mul(t["temp_jitter_c"], nt))
    rq = er.mul(er.from_int(rain), max(0, er.add(ONE, er.mul(t["rain_jitter"], nr))))
    return tq, rq


SENT_TMIN, SENT_TMAX = -60 << 32, 50 << 32
SENT_SLOPE, SENT_HAND = 100 << 32, 3000 << 32

CONDITIONS = ("temp", "rain", "elev", "slope", "hand", "coast", "rdist", "wet")


def check_rule_ranges(D):
    """The seam check of 4.1: every rule field of the land definitions with
    priority > 0, in B4's order, against its schema range; first failure
    fatal "biomes: rule: <field> outside its schema range"."""
    for _, d in D.ordered:
        for r in d["rules"]:
            for name, lo, hi in RULE_FIELDS:
                if not lo <= r[name] <= hi:
                    fatal("biomes: rule: %s outside its schema range" % name)


def rule_failures(r, sc, tq, rq, elev, s2, hand, coast, d34=FAR, wcount=0, wtotal=1, ws=ONE):
    """The conditions of B4 that rule r fails, as a tuple of names."""
    # Unbounded sentinels (4.1, amended 2026-11-17): a bound equal to the
    # extreme of its field's type skips that comparison.
    out = []
    lo_t, hi_t = r["temp_min_c"], r["temp_max_c"]
    if (lo_t != SENT_TMIN and tq < lo_t) or (hi_t != SENT_TMAX and tq > hi_t):
        out.append("temp")
    lo_r, hi_r = r["rain_min_mm"], r["rain_max_mm"]
    if (lo_r != 0 and rq < rb(sc, lo_r)) or (hi_r != 10000 and rq > rb(sc, hi_r)):
        out.append("rain")
    lo_e, hi_e = r["elev_min_m"], r["elev_max_m"]
    if (lo_e != 0 and elev < 10 * lo_e) or (hi_e != 3000 and elev > 10 * hi_e):
        out.append("elev")
    if r["slope_max"] != SENT_SLOPE and not not_steeper(s2, r["slope_max"]):
        out.append("slope")
    if r["hand_max_m"] != SENT_HAND and not (er.from_int(hand) <= er.mul_int(r["hand_max_m"], 10)):
        out.append("hand")
    if r["coast_max_m"] != 32767 and not (coast <= r["coast_max_m"]):
        out.append("coast")
    if r["river_dist_max_m"] != 32767 and not (16 * d34 <= 3 * r["river_dist_max_m"]):
        out.append("rdist")
    if r["wet_frac_min"] != 0 and not (need_of(r, ws) * wtotal <= wcount * ONE):
        out.append("wet")
    return tuple(out)


def lookup(D, sc, tq, rq, elev, s2, hand, coast, trace=None, d34=FAR, wcount=0, wtotal=1, ws=ONE):
    """B4 for a cell with water in {0, 1}: the code. trace, if given, gets
    (definition id, rule index, failures) for every rule tried, in order."""
    for k, d in D.ordered:
        for ri, r in enumerate(d["rules"]):
            f = rule_failures(r, sc, tq, rq, elev, s2, hand, coast, d34, wcount, wtotal, ws)
            if trace is not None:
                trace.append((k, ri, f))
            if not f:
                return d["code"]
    return D.fallback


def river_cells(w, h, water, b4):
    """B5 on a copy of the B4 grid; also returns (rivers, changed, ties,
    without a dry neighbour)."""
    out = list(b4)
    rivers = changed = ties = nodry = 0
    for i in range(w * h):
        if water[i] != WATER_RIVER:
            continue
        rivers += 1
        x, y = i % w, i // w
        count = {}
        for code in range(8):
            mx, my = x + DX[code], y + DY[code]
            if 0 <= mx < w and 0 <= my < h and water[my * w + mx] == WATER_DRY:
                v = b4[my * w + mx]
                count[v] = count.get(v, 0) + 1
        if not count:
            nodry += 1
            continue
        best = max(count.values())
        winners = sorted(v for v, c in count.items() if c == best)
        if len(winners) > 1:
            ties += 1
        out[i] = winners[0]
        if out[i] != b4[i]:
            changed += 1
    return out, (rivers, changed, ties, nodry)


def noise_at(key, x, y, rec):
    return er.fbm_m(key, (16 * x + 8) << 32, (16 * y + 8) << 32, rec)


def preconditions(w, h, layers):
    """Section 2, items 1 and 2 (item 3 is G7's)."""
    types = (("elevation", -32768, 32767), ("water", 0, 255), ("water_depth", 0, 65535), ("flow_dir", 0, 255),
             ("river", 0, 255), ("coast_dist", -32768, 32767), ("temperature", -32768, 32767),
             ("rainfall", 0, 65535))
    for name, lo, hi in types:
        a = layers.get(name)
        if a is None or len(a) != w * h:
            fatal(PRE + "layer '%s' missing or not %d x %d" % (name, w, h))
        if any(not lo <= v <= hi for v in a):
            fatal(PRE + "layer '%s' value outside its type" % name)
    if any(v > 3 for v in layers["water"]):
        fatal(PRE + "water value above 3")
    if any(v > 15 for v in layers["river"]):
        fatal(PRE + "river value above 15")


def biomes(w, h, L, D, t, seed, n=None, coverage=False):
    """B1 to B5 on a W x H grid. n: the map size for the scale rule (default
    max(W, H); see the reading in the golden header). Returns a dict of
    every intermediate."""
    preconditions(w, h, L)
    check_rule_ranges(D)
    e, water, depth, river, fd = L["elevation"], L["water"], L["water_depth"], L["river"], L["flow_dir"]
    coast, temp, rain = L["coast_dist"], L["temperature"], L["rainfall"]
    try:
        hand = hand_fifo(w, h, e, water, depth, river, fd, t["drain_river_class_min"])
    except FatalError as ex:
        fatal(PRE + str(ex))
    s2 = slope_s2(w, h, e)
    d34 = river_distance(w, h, water, river, t["river_dist_class_min"])
    wcount, wtotal = wet_share(w, h, water, hand, t["wet_hand_m"], t["wet_window_m"] // 16)
    n = max(w, h) if n is None else n
    sc = rain_scale(t, n)
    ws = wet_scale(t, n)
    ktj = cr.stream_key(seed, STREAM_TJ)
    krj = cr.stream_key(seed, STREAM_RJ)
    cells = w * h
    nt, nr, tq, rq, b4 = [0] * cells, [0] * cells, [0] * cells, [0] * cells, [0] * cells
    fails = {}
    fired = {}
    for i in range(cells):
        if water[i] == WATER_OCEAN:
            b4[i] = D.ocean
            continue
        if water[i] == WATER_LAKE:
            b4[i] = D.lake
            continue
        x, y = i % w, i // w
        nt[i] = noise_at(ktj, x, y, t["jitter_noise"])
        nr[i] = noise_at(krj, x, y, t["jitter_noise"])
        tq[i], rq[i] = jitter(temp[i], rain[i], nt[i], nr[i], t)
        tr = [] if coverage else None
        b4[i] = lookup(D, sc, tq[i], rq[i], e[i], s2[i], hand[i], coast[i], tr, d34[i], wcount[i], wtotal[i], ws)
        if coverage and water[i] == WATER_DRY:
            fired[b4[i]] = fired.get(b4[i], 0) + 1
            for k, ri, f in tr:
                if len(f) == 1:
                    key = (k, ri, f[0])
                    fails[key] = fails.get(key, 0) + 1
    biome, b5 = river_cells(w, h, water, b4)
    return {"w": w, "h": h, "L": L, "hand": hand, "s2": s2, "scale": sc, "wet_scale": ws, "d34": d34,
            "wet_count": wcount, "wet_total": wtotal, "nt": nt, "nr": nr, "tq": tq, "rq": rq,
            "b4": b4, "biome": biome, "b5": b5, "fails": fails, "fired": fired}


