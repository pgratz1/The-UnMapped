G7_PRE = "G7: "


def is_drain(water, river, i, k):
    return water[i] in (WATER_LAKE, WATER_OCEAN) or (water[i] == WATER_RIVER and river[i] >= k)


def down(w, h, i, code):
    if not 0 <= code <= 7:
        return None
    x, y = i % w + DX[code], i // w + DY[code]
    if 0 <= x < w and 0 <= y < h:
        return y * w + x
    return None


def surface(e, depth):
    return [e[i] + depth[i] for i in range(len(e))]


def hand_fifo(w, h, e, water, depth, river, flow_dir, k):
    """The reference method of G7 (D5): a FIFO queue from every drain cell in
    index order; popping c, each neighbour m in the 8-neighbour order that is
    not a drain and whose flow_dir points to c gets drain(m) = drain(c)."""
    if not 1 <= k <= 15:
        fatal(G7_PRE + "minimum river class %d outside 1..15" % k)
    n = w * h
    S = surface(e, depth)
    drain = [-1] * n
    q = deque()
    for i in range(n):
        if is_drain(water, river, i, k):
            drain[i] = i
            q.append(i)
    while q:
        c = q.popleft()
        x, y = c % w, c // w
        for code in range(8):
            mx, my = x + DX[code], y + DY[code]
            if not (0 <= mx < w and 0 <= my < h):
                continue
            m = my * w + mx
            if drain[m] != -1 or is_drain(water, river, m, k):
                continue
            if down(w, h, m, flow_dir[m]) == c:
                drain[m] = drain[c]
                q.append(m)
    out = [0] * n
    for i in range(n):
        if drain[i] == -1:
            fatal(G7_PRE + "cell %d reaches no drain cell along flow_dir" % i)
        out[i] = S[i] - S[drain[i]]
        if out[i] < 0:
            fatal(G7_PRE + "negative height above drainage at cell %d" % i)
    return out


def hand_recursive(w, h, e, water, depth, river, flow_dir, k):
    """A second G7: drain(c) by following flow_dir from each cell (with a
    step limit as cycle detection), memoised. Independent of the FIFO."""
    n = w * h
    S = surface(e, depth)
    drain = [None] * n
    for s in range(n):
        path = []
        c = s
        while drain[c] is None and not is_drain(water, river, c, k):
            path.append(c)
            if len(path) > n:
                fatal(G7_PRE + "flow_dir cycle")
            nxt = down(w, h, c, flow_dir[c])
            if nxt is None:
                fatal(G7_PRE + "flow_dir leaves the map or has no downstream at cell %d" % c)
            c = nxt
        d = drain[c] if drain[c] is not None else c
        for p in path:
            drain[p] = d
        drain[c] = d
    out = [S[i] - S[drain[i]] for i in range(n)]
    if any(v < 0 for v in out):
        fatal(G7_PRE + "negative")
    return out


