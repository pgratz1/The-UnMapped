_FMT = {1: "B", 3: "H", 4: "h", 5: "I"}


def _pack(fmt, values):
    a = array(fmt, values)
    if sys.byteorder != "little":
        a.byteswap()
    return a.tobytes()


def h_i64(values):
    return hashlib.sha256(_pack("q", values)).hexdigest()


def layer_hash(w, h, code, values):
    head = w.to_bytes(4, "little") + h.to_bytes(4, "little") + bytes([code])
    return hashlib.sha256(head + _pack(_FMT[code], values)).hexdigest()


def table_hash(ncols, rows):
    """P0-04 8 logical hash of a table: u64 column count, then each row in
    primary-key order, each column as a tagged value."""
    out = bytearray(struct.pack("<Q", ncols))
    for row in rows:
        for v in row:
            if v is None:
                out += b"\x00"
            elif isinstance(v, int):
                out += b"\x01" + struct.pack("<q", v)
            elif isinstance(v, str):
                b = v.encode("utf-8")
                out += b"\x03" + struct.pack("<Q", len(b)) + b
            else:
                raise TypeError(v)
    return hashlib.sha256(bytes(out)).hexdigest()


def biome_table_hash(D):
    return table_hash(5, D.table_rows())


def climate_table_hash(wind):
    return table_hash(2, [(1, wind)])


