class Defs:
    """Derived views of a definition set: water codes, the fallback, the
    land definitions with priority > 0 in descending priority."""

    def __init__(self, defs):
        self.defs = defs
        self.by_code = {d["code"]: (k, d) for k, d in defs.items()}
        self.ocean = [d["code"] for d in defs.values() if d["water_body"] == "ocean"][0]
