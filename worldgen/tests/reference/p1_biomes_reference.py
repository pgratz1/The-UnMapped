def ratio4(a, b):
    if b == 0:
        return "n/a"
    v = cr.rha(a * 10000, b)
    return "%d.%04d" % (v // 10000, v % 10000)


def biome_share(biome, rows):
    land_codes = [r[0] for r in rows if r[4] == 0]
    den = sum(1 for v in biome if v in land_codes)
    return " ".join("%s:%s" % (r[1], ratio4(sum(1 for v in biome if v == r[0]), den)) for r in rows if r[4] == 0)


def biome_patches(w, h, biome, rows):
    land_codes = set(r[0] for r in rows if r[4] == 0)
    mask = [1 if v in land_codes else 0 for v in biome]
    label, comps = er.g2_components(w, h, mask, 8, biome)
    return len(comps)


