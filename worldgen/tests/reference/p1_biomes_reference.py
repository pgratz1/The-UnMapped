# golden header): 40 x 40, a one-cell ocean border (e = -20), interior zones
# by column x: lowland (x <= 13), ramp (14..19), plateau at about 210 m
# (20..27), mountain (28..38). Per cell, in index order, three draws from
# Rng(substream(stream_key(0, "test.biomes"), f)): u_e = uniform_i64(0, 60),
# u_t = uniform_i64(-15, 15), u_r = uniform_i64(-40, 40) (drawn for border
# cells too, then discarded).
#   lowland   e = 3 + x + u_e mod 4
#   ramp      e = 17 + 350 (x - 13) + u_e mod 41
#   plateau   e = 2105 + u_e mod 5
#   mountain  e = 2110 + 110 (x - 27)^2 + u_e
#   ocean     e = -20
#   temperature = BASE[f] - (65 max(e, 0)) div 10000 + u_t  (tenths, floor division)
#   rainfall    = 380 + 18 y + u_r                          (mm)
# Hydrology: the reference of P1-02 with river_min_area_m2 2560 (T = 10
# cells) and t = 0 (no tie), giving water, water_depth, flow_dir, river and
# coast_dist. The world seed of the biome stage is f.
DESIGNED_W = 40
DESIGNED_BASE = (90, 60, 20, 0)
DESIGNED_AREA = 2560


def designed_elevation(f):
    rng = cr.Rng(cr.substream(cr.stream_key(0, STREAM_TEST), f))
    w = h = DESIGNED_W
    e, ut, ur = [], [], []
    for i in range(w * h):
        x, y = i % w, i // w
        a = rng.uniform_i64(0, 60)
        b = rng.uniform_i64(-15, 15)
        c = rng.uniform_i64(-40, 40)
        ut.append(b)
        ur.append(c)
        if x == 0 or y == 0 or x == w - 1 or y == h - 1:
            e.append(-20)
        elif x <= 13:
            e.append(3 + x + a % 4)
        elif x <= 19:
            e.append(17 + 350 * (x - 13) + a % 41)
        elif x <= 27:
            e.append(2105 + a % 5)
        else:
            e.append(2110 + 110 * (x - 27) ** 2 + a)
    return w, h, e, ut, ur


def designed_layers(f):
    import p1_hydrology_reference as hr
    w, h, e, ut, ur = designed_elevation(f)
    r = hr.hydrology(w, h, e, DESIGNED_AREA, None)
    L = {"elevation": e}
    for name in ("water", "water_depth", "flow_dir", "river", "coast_dist"):
        L[name] = hr.layer(r, name)
    base = DESIGNED_BASE[f % len(DESIGNED_BASE)]
    L["temperature"] = [base - (65 * max(e[i], 0)) // 10000 + ut[i] for i in range(w * h)]
    L["rainfall"] = [380 + 18 * (i // w) + ur[i] for i in range(w * h)]
    return w, h, L


