# G8: cell slope (P1-00 7.8 and 10.3 "Cell slope")
# ---------------------------------------------------------------------------

def slope_s2(w, h, e):
    ep = [max(v, 0) for v in e]
    out = [0] * (w * h)
    for y in range(h):
        ya, yb = max(y - 1, 0), min(y + 1, h - 1)
        for x in range(w):
            xa, xb = max(x - 1, 0), min(x + 1, w - 1)
            gx = (ep[y * w + xb] - ep[y * w + xa]) * (2 // (xb - xa)) if xb > xa else 0
            gy = (ep[yb * w + x] - ep[ya * w + x]) * (2 // (yb - ya)) if yb > ya else 0
            out[y * w + x] = gx * gx + gy * gy
    return out


def not_steeper(s2, t_raw):
    """G8: S2 x 2^64 <= (320 x t.raw)^2."""
    return s2 * (1 << 64) <= (320 * t_raw) ** 2


