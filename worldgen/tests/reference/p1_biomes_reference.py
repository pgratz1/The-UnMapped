        global CLIMATE_GOLDEN
        args = []
        db_dir = None
        it = iter(argv[2:])
        for a in it:
            if a == "--db-dir":
                db_dir = next(it)
            elif a == "--climate-golden":
                CLIMATE_GOLDEN = next(it)
            elif not a.startswith("--"):
                args.append(a)
