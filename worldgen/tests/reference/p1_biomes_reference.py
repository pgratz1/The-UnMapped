def world_layers(fixture, n, seed, legacy=False):
    """The eight input layers of a world, its wind and its offset, from the
    hydrology and climate references (flat_tie of the seed, shipped
    hydrology and climate tuning; elevation fixture shipped or small;
    legacy: the 0.8.0 climate, coast_rain_mm 75 and no offset)."""
    import p1_climate_reference as clr
    import p1_hydrology_reference as hr
    e = hr.elevation_of(fixture, n, seed)
    # A cached elevation grid must equal the hydrology golden value of the
    # world (a stale cache gave a wrong 48 seed 3 case once).
    want = clr._hydrology_golden_elevation().get((fixture, n, seed))
    if want is not None and layer_hash(n, n, 4, e) != want:
        fatal("elevation input of %s %d %d differs from the hydrology golden value (stale cache?)" % (fixture, n, seed))
    tie =hr.flat_tie(seed, n, n, [1 if v < 0 else 0 for v in e])
    r = hr.hydrology(n, n, e, 125000, tie)
    L = {"elevation": e}
    for name in ("water", "water_depth", "flow_dir", "river", "coast_dist"):
        L[name] = hr.layer(r, name)
    ct = clr.legacy_tuning() if legacy else clr.shipped_tuning()
    c = clr.climate(n, n, e, L["water"], L["water_depth"], L["coast_dist"], ct, seed)
    L["temperature"] = c["temperature"]
    L["rainfall"] = c["rainfall"]
    return L, c["wind"], c["offset_dc"]


def decode_blob(blob):
    sys.path.insert(0, _HERE)
    import p0_world_check as pw
    tcode, codec, width, height, values = pw.decode_blob(blob)
    return tcode, width, height, values


def db_layers(path):
    """Every layer of a world file, decoded: {name: (w, h, tcode, values)}."""
    con = sqlite3.connect("file:%s?mode=ro" % path, uri=True)
    try:
        out = {}
        for name, data in con.execute("SELECT name, data FROM layer ORDER BY id"):
            tcode, w, h, values = decode_blob(bytes(data))
            out[name] = (w, h, tcode, list(values))
        return out
    finally:
        con.close()


CLIMATE_GOLDEN = os.path.join(_HERE, "..", "golden", "p1-03-climate.txt")


def climate_golden_items():
    """{case name: {item: value}} of p1-03-climate.txt (or of the file named
    by --climate-golden)."""
    path = CLIMATE_GOLDEN
    out = {}
    with open(path) as f:
        for line in f:
            tok = line.split()
            if not tok or tok[0].startswith("#"):
                continue
            if tok[0] == "case":
                out[tok[1]] = {}
            else:
                out[tok[0]][tok[1]] = tok[2]
    return out


def layers_from_db(path, climate_case, upstream_only=False):
    """The eight input layers of a world file (upstream_only: the six
    elevation and hydrology layers), each checked against the layer hashes
    of the climate golden case (so equal to the references')."""
    raw = db_layers(path)
    golden = climate_golden_items()[climate_case]
    L = {}
    n = None
    for name, code in LAYER_TYPES:
        if upstream_only and name in ("temperature", "rainfall"):
            continue
        w, h, tcode, values = raw[name]
        if tcode != code:
            fatal("%s: layer %s has type %d" % (path, name, tcode))
        n = w
        L[name] = values
        if name in golden and layer_hash(w, h, code, values) != golden[name]:
            fatal("%s: layer %s differs from p1-03-climate.txt case %s" % (path, name, climate_case))
    for name in ("flow_dir", "river"):
        if name in golden:
            continue
    return n, L


def hydro_golden_check(fixture, n, seed, L):
    """flow_dir and river are not items of the climate golden file: check them
    against the hydrology golden file when it has the world."""
    path = os.path.join(_HERE, "..", "golden", "p1-02-hydrology.txt")
    cases = {}
    with open(path) as f:
        for line in f:
            tok = line.split()
            if not tok or tok[0].startswith("#"):
                continue
            if tok[0] == "case":
                cases[tok[1]] = (tok[2], int(tok[3]), int(tok[4]), {})
            elif tok[0] in cases:
                cases[tok[0]][3][tok[1]] = tok[2]
    for name, (fx, nn, s, items) in cases.items():
        if (fx, nn, s) == (fixture, n, seed) and "flow_dir" in items:
            for lname, code in (("flow_dir", 1), ("river", 1)):
                if lname in items and layer_hash(n, n, code, L[lname]) != items[lname]:
                    fatal("%s differs from p1-02-hydrology.txt case %s" % (lname, name))
            return name
    return None


