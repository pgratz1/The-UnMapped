def erosion_params(t, key):
    D_o = mul_int(t["talus_slope"], 16)
    return {"iterations": t["erosion_iterations"], "route_interval": t["erosion_route_interval"],
            "k": t["erosion_k"], "diffusion": t["erosion_diffusion"], "D_o": D_o,
            "D_d": mul(D_o, SQRT2), "talus_rate": t["talus_rate"], "floor": t["land_floor_m"],
            "key": key}


def random_receivers(w, h, L, ocean, rcv, key, it, trace=None):
    tab = nbt(w, h)
    for c in range(w * h):
        if ocean[c]:
            continue
        lc = L[c]
        wts = [0] * 8
        W = 0
        for code, m in tab[c]:
            if L[m] >= lc:
                continue
            q = (lc - L[m]) >> 16
            wv = q * q if code & 1 else 2 * q * q
            wts[code] = wv
            W += wv
        if W > 0:
            hv = hash_at(key, c, it)
            r = hv % W
            acc = 0
            chosen = None
            for code in range(8):
                acc += wts[code]
                if wts[code] != 0 and acc > r:
                    chosen = code
                    break
            rcv[c] = chosen
            if trace is not None:
                trace.append((c, wts, W, hv, r, chosen))
    return rcv


def erode(w, h, hgrid, ocean, p, trace=None):
    n = w * h
    hgrid = list(hgrid)
    hn = [0] * n
    F = [0] * n
    tab = nbt(w, h)
    flo = p["floor"]
    kk = p["k"]
    D = p["diffusion"]
    rate = p["talus_rate"]
    D_o, D_d = p["D_o"], p["D_d"]
    order = rcv = None
    for it in range(p["iterations"]):
        if it % p["route_interval"] == 0:
            L, parent, order = g3_flood(w, h, hgrid, ocean)
            rcv = g4_receivers(w, h, L, parent, ocean)
            if trace is not None:
                trace["order"] = list(order)
                trace["g4"] = list(rcv)
                trace["rand"] = []
            random_receivers(w, h, L, ocean, rcv, p["key"], it,
                             trace["rand"] if trace is not None else None)
            A = g5_accumulate(w, h, rcv, ocean, order)
            for c in range(n):
                if ocean[c]:
                    F[c] = 0
                    continue
                S = isqrt_u64(A[c] << 32) << 16
                fc = mul(kk, S)
                if rcv[c] & 1:
                    fc = mul(fc, INV_SQRT2)
                F[c] = fc
            if trace is not None:
                trace["rcv"] = list(rcv)
                trace["A"] = list(A)
                trace["F"] = list(F)
        # E8.4 solve
        for c in order:
            if ocean[c]:
                hn[c] = hgrid[c]
                continue
            m = neighbour_of(w, h, c, rcv[c])
            base = 0 if ocean[m] else hn[m]
            hc = hgrid[c]
            if hc > base:
                v = add(base, div(sub(hc, base), add(ONE, F[c])))
            else:
                v = hc
            hn[c] = v if v > flo else flo
        if trace is not None:
            trace["hn"] = list(hn)
        # E8.5 diffusion
        for c in range(n):
            if ocean[c]:
                hgrid[c] = hn[c]
                continue
            x, y = c % w, c // w
            hc = hn[c]
            S4 = 0
            for code in N4:
                xx, yy = x + DX[code], y + DY[code]
                if not (0 <= xx < w and 0 <= yy < h):
                    S4 = add(S4, hc)
                else:
                    m = yy * w + xx
                    if not ocean[m]:
                        S4 = add(S4, hn[m])
            v = add(hc, mul(D, sub(S4, mul_int(hc, 4))))
            hgrid[c] = v if v > flo else flo
        if trace is not None:
            trace["hd"] = list(hgrid)
        # E8.6 talus
        tt = list(hgrid)
        for c in range(n):
            if ocean[c]:
                continue
            hc = hgrid[c]
            delta = 0
            for code, m in tab[c]:
                hm = 0 if ocean[m] else hgrid[m]
                Dk = D_d if code & 1 else D_o
                xv = sub(hc, hm)
                if xv > Dk:
                    delta = sub(delta, mul(rate, sub(xv, Dk)))
                elif (not ocean[m]) and -xv > Dk:
                    delta = add(delta, mul(rate, sub(-xv, Dk)))
            v = add(hc, delta)
            tt[c] = v if v > flo else flo
        hgrid = tt
    return hgrid


