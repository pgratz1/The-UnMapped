def _pack(fmt, values):
    a = array(fmt, values)
    if sys.byteorder != "little":
        a.byteswap()
    return a.tobytes()


def h_i64(values):
    return hashlib.sha256(_pack("q", values)).hexdigest()


def h_u8(values):
    return hashlib.sha256(bytes(values)).hexdigest()


def h_i16(values):
    return hashlib.sha256(_pack("h", values)).hexdigest()


def layer_hash(n, values):
    head = n.to_bytes(4, "little") + n.to_bytes(4, "little") + bytes([4])
    return hashlib.sha256(head + _pack("h", values)).hexdigest()


def world_items(r):
    """The golden items of one world, in step order: (name, value text)."""
    f = r["fields"]
    hts = r["heights"]
    fl = hts["floor"]
    info = r["info"]
    items = [
        ("centre", "%d,%d" % (f["cx"], f["cy"])),
        ("c", h_i64(f["c"])),
        ("nb", h_i64(f["nb"])),
        ("ns", h_i64(f["ns"])),
        ("c_sea", str(f["c_sea"])),
        ("w_b", str(f["w_b"])),
        ("s_land", str(f["s_land"])),
        ("ocean", h_u8(r["O"])),
        ("land_cells", str(r["L_O"])),
        ("floor", "%d,%d,%d,%d" % (1 if fl["triggered"] else 0, fl["target"], fl["o"], fl["beta"])),
        ("scale", str(hts["scale"])),
        ("h7", h_i64(hts["h7"])),
        ("h8", h_i64(r["h8"])),
        ("e", h_i16(r["e"])),
        ("max_share", str(r["max_share"])),
        ("depressions", str(len(info["stats"]))),
        ("candidates", ",".join(str(x) for x in info["candidates"]) or "-"),
        ("kept", ",".join(str(x) for x in info["kept_labels"]) or "-"),
        ("kept_cells", str(info["kept_cells"])),
        ("e_final", h_i16(r["e_final"])),
        ("layer", layer_hash(r["n"], r["e_final"])),
    ]
    return items


