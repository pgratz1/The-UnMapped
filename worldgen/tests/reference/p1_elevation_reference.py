def ocean_depth_of_dl(dl, t):
    dist_m = div_int(from_int(16 * min(dl, 1 << 20)), 5)
    q = div(dist_m, add(dist_m, t["ocean_shelf_m"]))
    return -(HALF + mul(t["ocean_depth_m"], q))


def heights(seed, n, t, f, O, fl=None):
    K = keys_for(seed)
    if fl is None:
        fl = floor_for_world(n, t, f, O)
    o_star, beta = fl["o"], fl["beta"]
    c_sea, s_land, w_b = f["c_sea"], f["s_land"], f["w_b"]
    N2 = n * n
    h0 = [0] * N2
    unit = [0] * N2
    contrast = t["segment_contrast"]
    for i in range(N2):
        if O[i]:
            continue
        x, y = i % n, i // n
        X = from_int(16 * x + 8)
        Y = from_int(16 * y + 8)
        tl = coast_tl(f["c"][i], c_sea, s_land)
        gm = gm_of(tl, t["mountain_coast_t"])
        co = div(tl, add(ONE, tl))
        un = fbm_m(K["basin"], X, Y, t["basin_noise"])
        base = add(mul(t["lowland_height_m"], co), mul(mul(t["basin_amp_m"], un), co))
        mask = mask_of(f["nb"][i], f["ns"][i], gm, o_star, beta, w_b, contrast)
        qx = add(X, mul(t["relief_warp_amp_m"], fbm_m(K["relief_warp_x"], X, Y, t["relief_warp"])))
        qy = add(Y, mul(t["relief_warp_amp_m"], fbm_m(K["relief_warp_y"], X, Y, t["relief_warp"])))
        if mask > 0:
            ridge = ridged_m(K["ridge"], qx, qy, t["ridge_noise"], t["ridge_weight"])
            ff = t["foothill_fraction"]
            profile = add(ff, mul(ONE - ff, ridge))
            u = mul(mask, profile)
        else:
            u = 0
        hh = fbm_m(K["hills"], qx, qy, t["hill_noise"])
        rn = fbm_m(K["roughness"], X, Y, t["roughness_noise"])
        rmin = t["roughness_min"]
        rho = add(rmin, mul(ONE - rmin, fade(clamp(HALF + rn, 0, ONE))))
        hcm = t["hill_coast_min"]
        hf = add(hcm, mul(ONE - hcm, co))
        hills = mul(t["hill_height_m"], mul(mul(hh, rho), hf))
        det = mul(t["detail_amp_m"], fbm_m(K["detail"], X, Y, t["detail_noise"]))
        h0[i] = add(add(base, hills), det)
        unit[i] = u
    # E5.3
    land = bytearray(1 - O[i] for i in range(N2))
    dl = chamfer(n, n, land)
    # E6
    Ul = [unit[i] for i in range(N2) if not O[i]]
    q = quantile(Ul, t["mountain_peak_rank"])
    qc = quantile(Ul, t["mountain_cover_rank"])
    mh = t["mountain_height_m"]
    cap = mul_int(mh, 3)
    ps = div(mh, q) if mul_int(q, 3) > ONE else cap
    ch = t["mountain_cover_height_m"]
    scale = div(ch, qc) if (qc > 0 and mul(ps, qc) > ch) else ps
    # E7
    fl_m = t["land_floor_m"]
    h = [0] * N2
    for i in range(N2):
        if O[i]:
            h[i] = ocean_depth_of_dl(dl[i], t)
        else:
            h[i] = clamp(add(h0[i], mul(scale, unit[i])), fl_m, H_MAX)
    return {"h7": h, "scale": scale, "floor": fl, "q": q, "qc": qc}


