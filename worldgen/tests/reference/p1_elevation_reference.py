def depths_for(size, depth, volume):
    """size depths in [1, depth] with max = depth and sum = volume."""
    ds = [depth] + [1] * (size - 1)
    rest = volume - sum(ds)
    i = 1
    while rest > 0:
        add_ = min(rest, depth - ds[i])
        ds[i] += add_
        rest -= add_
        i += 1
    assert max(ds) == depth and sum(ds) == volume and len(ds) == size
    return ds


def selection_grid():
    """The grid of the E10.3 selection test: eight pits in rows of a rim."""
    R = 100
    w = 18
    h = 2 + 2 * len(SEL_COMPONENTS) + 1
    e = []
    for y in range(h):
        for x in range(w):
            e.append(-5 if (x == 0 or y == 0 or x == w - 1 or y == h - 1) else R)
    for k, (size, depth, vol) in enumerate(SEL_COMPONENTS):
        y = 2 + 2 * k
        for j, dd in enumerate(depths_for(size, depth, vol)):
            e[y * w + 2 + j] = R - dd
    return w, h, e


