def ocean_from_provisional(w, h, P, i_min):
    """E4 steps 2 and 3 on any W x H grid; returns the ocean mask (bytes)."""
    n = w * h
    label, comps = g2_components(w, h, P, 4)
    edge_label = set()
    for i in range(n):
        x, y = i % w, i // w
        if (x == 0 or y == 0 or x == w - 1 or y == h - 1) and label[i]:
            edge_label.add(label[i])
    O = bytearray(n)
    for i in range(n):
        if label[i] in edge_label:
            O[i] = 1
    land = bytearray(1 - O[i] for i in range(n))
    llabel, lcomps = g2_components(w, h, land, 8)
    ok = False
    for cells in lcomps:
        if len(cells) < i_min:
            for c in cells:
                O[c] = 1
        else:
            ok = True
    if not ok:
        fatal("elevation: no land")
    return O


def classify(n, t, f):
    M = derived(t, n)["M"]
    c_sea = f["c_sea"]
    c = f["c"]
    P = bytearray(n * n)
    for i in range(n * n):
        x, y = i % n, i // n
        if c[i] <= c_sea or min(x, y, n - 1 - x, n - 1 - y) < M:
            P[i] = 1
    return ocean_from_provisional(n, n, P, derived(t, n)["I_min"])


