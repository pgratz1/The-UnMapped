def _fx_text(v):
    if isinstance(v, int):
        return from_int(v)
    return cr.parse_decimal(v)


def make_tuning(overrides=None):
    """Tuning as a dict of raw values (Fx raw for fx fields)."""
    t = {}
    for name, v in SHIPPED_TEXT:
        if overrides and name in overrides:
            v = overrides[name]
        if isinstance(v, tuple):
            if v[0] == "map":
                t[name] = (_fx_text(v[1]), v[2], _fx_text(v[3]))
            else:
                t[name] = (v[1], v[2], _fx_text(v[3]))
        elif name in INT_FIELDS:
            t[name] = v
        else:
            t[name] = _fx_text(v)
    return t


