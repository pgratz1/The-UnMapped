class Checker:
    def __init__(self):
        self.fails = 0
        self.passes = 0

    def eq(self, what, got, want):
        if got == want:
            self.passes += 1
        else:
            self.fails += 1
            print("FAIL %s: got %r, want %r" % (what, got, want))


