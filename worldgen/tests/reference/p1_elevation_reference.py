DX = (1, 1, 0, -1, -1, -1, 0, 1)
DY = (0, 1, 1, 1, 0, -1, -1, -1)
N4 = (0, 2, 4, 6)


def quantile_rank(q, n):
    if n == 0:
        fatal("quantile of nothing")
    return min(n - 1, (q * n) >> 32)


def kth(values, k):
    return sorted(values)[k]


def quantile(values, q):
    return kth(values, quantile_rank(q, len(values)))


def neighbours_table(w, h):
    """nb[i] = list of (code, j) for existing neighbours, 8-neighbour order."""
    tab = []
    for i in range(w * h):
        x, y = i % w, i // w
        row = []
        for code in range(8):
            xx, yy = x + DX[code], y + DY[code]
            if 0 <= xx < w and 0 <= yy < h:
                row.append((code, yy * w + xx))
        tab.append(row)
    return tab


_NB_CACHE = {}


def nbt(w, h):
    k = (w, h)
    if k not in _NB_CACHE:
        _NB_CACHE[k] = neighbours_table(w, h)
    return _NB_CACHE[k]


def g2_components(w, h, mask, conn, keys=None):
    """G2: labels (0 = not in P), in order of minimum index, FIFO BFS."""
    n = w * h
    label = [0] * n
    tab = nbt(w, h)
    comps = []  # list of lists of cells in BFS order
    nxt = 0
    for s in range(n):
        if not mask[s] or label[s]:
            continue
        nxt += 1
        label[s] = nxt
        q = deque([s])
        cells = []
        while q:
            c = q.popleft()
            cells.append(c)
            for code, m in tab[c]:
                if conn == 4 and (code & 1):
                    continue
                if mask[m] and not label[m] and (keys is None or keys[m] == keys[c]):
                    label[m] = nxt
                    q.append(m)
        comps.append(cells)
    return label, comps


def g3_flood(w, h, keys, ocean):
    """G3 routing flood: (L, parent, order)."""
    n = w * h
    L = [0] * n
    parent = [8] * n
    visited = bytearray(n)
    heap = []
    seq = 0
    any_ocean = False
    for i in range(n):
        if ocean[i]:
            any_ocean = True
            visited[i] = 1
            heap.append((0, seq, i))
            seq += 1
        elif keys[i] < 1:
            fatal("G3: land key below 1")
    if not any_ocean:
        fatal("G3: no ocean")
    heapq.heapify(heap)
    tab = nbt(w, h)
    order = []
    push = heapq.heappush
    pop = heapq.heappop
    while heap:
        k, _, c = pop(heap)
        order.append(c)
        lc = L[c]
        for code, m in tab[c]:
            if visited[m]:
                continue
            visited[m] = 1
            km = keys[m]
            lm = km if km > lc else lc
            L[m] = lm
            parent[m] = (code + 4) & 7
            push(heap, (lm, seq, m))
            seq += 1
    return L, parent, order


def g4_receivers(w, h, L, parent, ocean):
    n = w * h
    tab = nbt(w, h)
    rcv = [8] * n
    for c in range(n):
        if ocean[c]:
            continue
        lc = L[c]
        best = -1
        best_s = 0
        for code, m in tab[c]:
            lm = L[m]
            if lm < lc:
                d = lc - lm
                s = d * d * (1 if code & 1 else 2)
                if s > best_s:
                    best_s = s
                    best = code
        rcv[c] = best if best >= 0 else parent[c]
    return rcv


def neighbour_of(w, h, c, code):
    x, y = c % w + DX[code], c // w + DY[code]
    if 0 <= x < w and 0 <= y < h:
        return y * w + x
    return -1


def g5_accumulate(w, h, rcv, ocean, order):
    n = w * h
    A = [0] * n
    for c in range(n):
        if not ocean[c]:
            A[c] = 1
    for c in reversed(order):
        if ocean[c]:
            continue
        m = neighbour_of(w, h, c, rcv[c])
        if m < 0:
            fatal("G5: receiver off the grid")
        if not ocean[m]:
            A[m] += A[c]
    return A


def chamfer(w, h, source):
    n = w * h
    d = [0 if source[i] else INF for i in range(n)]
    fwd = ((-1, 0, 5), (-1, -1, 7), (0, -1, 5), (1, -1, 7))
    bwd = ((1, 0, 5), (1, 1, 7), (0, 1, 5), (-1, 1, 7))
    for i in range(n):
        x, y = i % w, i // w
        v = d[i]
        for dx, dy, wt in fwd:
            xx, yy = x + dx, y + dy
            if 0 <= xx < w and 0 <= yy < h:
                u = d[yy * w + xx] + wt
                if u < v:
                    v = u
        d[i] = v
    for i in range(n - 1, -1, -1):
        x, y = i % w, i // w
        v = d[i]
        for dx, dy, wt in bwd:
            xx, yy = x + dx, y + dy
            if 0 <= xx < w and 0 <= yy < h:
                u = d[yy * w + xx] + wt
                if u < v:
                    v = u
        d[i] = v
    return d


