_GRAD_CACHE = {}


def _grad(key, xi, yi):
    k = (key, xi, yi)
    g = _GRAD_CACHE.get(k)
    if g is None:
        g = hash_at(key, xi, yi) >> 61
        if len(_GRAD_CACHE) > 4000000:
            _GRAD_CACHE.clear()
        _GRAD_CACHE[k] = g
    return g


def _gd(g, u, v):
    if g == 0:
        return u + v
    if g == 1:
        return -u + v
    if g == 2:
        return u - v
    if g == 3:
        return -u - v
    if g == 4:
        return u
    if g == 5:
        return -u
    if g == 6:
        return v
    return -v


def noise2(key, x, y):
    xi = x >> 32
    yi = y >> 32
    fx = x & 0xFFFFFFFF
    fy = y & 0xFFFFFFFF
    d00 = _gd(_grad(key, xi, yi), fx, fy)
    d10 = _gd(_grad(key, xi + 1, yi), fx - ONE, fy)
    d01 = _gd(_grad(key, xi, yi + 1), fx, fy - ONE)
    d11 = _gd(_grad(key, xi + 1, yi + 1), fx - ONE, fy - ONE)
    su = fade(fx)
    sv = fade(fy)
    nx0 = d00 + mul(d10 - d00, su)
    nx1 = d01 + mul(d11 - d01, su)
    n = nx0 + mul(nx1 - nx0, sv)
    return -ONE if n < -ONE else ONE if n > ONE else n


_SUB_CACHE = {}


def _sub(key, o):
    k = (key, o)
    v = _SUB_CACHE.get(k)
    if v is None:
        v = substream(key, o)
        _SUB_CACHE[k] = v
    return v


def fbm2(key, x, y, octaves, base_freq, lacunarity, gain):
    if not (1 <= octaves <= 16):
        fatal("octaves")
    if base_freq <= 0 or lacunarity <= 0 or gain <= 0 or gain > ONE:
        fatal("fbm2 params")
    s = 0
    norm = 0
    amp = ONE
    f = base_freq
    for o in range(octaves):
        n = noise2(_sub(key, o), mul(x, f), mul(y, f))
        s = add(s, mul(amp, n))
        norm = add(norm, amp)
        amp = mul(amp, gain)
        f = mul(f, lacunarity)
    r = div(s, norm)
    return -ONE if r < -ONE else ONE if r > ONE else r


# Noise records (P1-01 4.1): fbm_map (cycles, octaves, gain) and fbm_m
# (wavelength_m, octaves, gain), held as tuples.

def fbm_map(key, a, b, rec):
    cycles, octaves, gain = rec
    return fbm2(key, a, b, octaves, cycles, LAC, gain)


def fbm_m(key, a, b, rec):
    wl, octaves, gain = rec
    return fbm2(key, a, b, octaves, from_ratio(1, wl), LAC, gain)


def ridged_m(key, a, b, rec, weight):
    wl, octaves, gain = rec
    f = from_ratio(1, wl)
    amp = ONE
    wgt = ONE
    s_sum = 0
    norm = 0
    for o in range(octaves):
        xs = mul(a, f)
        ys = mul(b, f)
        n = noise2(_sub(key, o), xs, ys)
        s = ONE - abs(n)
        s = mul(s, s)
        s = mul(s, wgt)
        wgt = clamp(mul(s, weight), 0, ONE)
        s_sum = add(s_sum, mul(s, amp))
        norm = add(norm, amp)
        amp = mul(amp, gain)
        f = mul(f, LAC)
    return clamp(div(s_sum, norm), 0, ONE)


