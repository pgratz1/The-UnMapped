def continent_centre(seed, t):
    K = stream_key(seed, "geo.elevation.continent")
    out = []
    for k in (0, 1):
        hv = hash_at(K, k, 0) >> 32
        out.append(HALF + mul(t["continent_center_jitter"], (hv - (1 << 31)) * 2))
    return out[0], out[1]


def jitter_of_hv(hv, jitter):
    return HALF + mul(jitter, (hv - (1 << 31)) * 2)


def e2_cell(x, y, n, t, K, cx, cy):
    X = from_int(16 * x + 8)
    Y = from_int(16 * y + 8)
    U = from_ratio(2 * x + 1, 2 * n)
    V = from_ratio(2 * y + 1, 2 * n)
    wx = fbm_map(K["continent_warp_x"], U, V, t["continent_warp"])
    wy = fbm_map(K["continent_warp_y"], U, V, t["continent_warp"])
    Uw = add(U, mul(t["continent_warp_amp_frac"], wx))
    Vw = add(V, mul(t["continent_warp_amp_frac"], wy))
    d = mul_int(hypot(sub(Uw, cx), sub(Vw, cy)), 2)
    nc = fbm_map(K["continent"], Uw, Vw, t["continent_noise"])
    Uf = add(U, div_int(sub(Uw, U), 2))
    Vf = add(V, div_int(sub(Vw, V), 2))
    ed = min(min(Uf, Vf), min(ONE - Uf, ONE - Vf))
    ena = t["edge_noise_amp"]
    edn = add(ed, mul(ena, nc))
    fe = fade(clamp(div(edn, t["edge_falloff_frac"]), 0, ONE))
    dm = sub(mul_int(hypot(Uf - HALF, Vf - HALF), 2), mul(ena, nc))
    fr = fade(clamp(div(sub(dm, t["edge_radial_start"]),
                        sub(t["edge_radial_end"], t["edge_radial_start"])), 0, ONE))
    edge = mul(t["edge_falloff_depth"], max(ONE - fe, fr))
    cd = fbm_m(K["coast"], X, Y, t["coast_noise"])
    c = add(sub(add(ONE - d, mul(t["continent_noise_amp"], nc)), edge), mul(t["coast_noise_amp"], cd))
    nb = fbm_map(K["belt"], Uw, Vw, t["belt_noise"])
    ns = fbm_map(K["segment"], Uw, Vw, t["segment_noise"])
    return c, nb, ns


def belt_gradient(n, nb):
    g = [0] * (n * n)
    for y in range(n):
        y0 = max(y - 1, 0)
        y1 = min(y + 1, n - 1)
        for x in range(n):
            x0 = max(x - 1, 0)
            x1 = min(x + 1, n - 1)
            gx = div_int(nb[y * n + x1] - nb[y * n + x0], x1 - x0)
            gy = div_int(nb[y1 * n + x] - nb[y0 * n + x], y1 - y0)
            g[y * n + x] = hypot(gx, gy)
    return g


def belt_gradient_wh(w, h, nb):
    g = [0] * (w * h)
    for y in range(h):
        y0 = max(y - 1, 0)
        y1 = min(y + 1, h - 1)
        for x in range(w):
            x0 = max(x - 1, 0)
            x1 = min(x + 1, w - 1)
            gx = div_int(nb[y * w + x1] - nb[y * w + x0], x1 - x0)
            gy = div_int(nb[y1 * w + x] - nb[y0 * w + x], y1 - y0)
            g[y * w + x] = hypot(gx, gy)
    return g


def coast_threshold(c, land_fraction):
    return quantile(c, ONE - land_fraction)


def land_scale(c, c_sea):
    vals = [v - c_sea for v in c if v > c_sea]
    if not vals:
        fatal("elevation: no land")
    return max(1, kth(vals, quantile_rank(HALF, len(vals))))


def belt_width(g_med, hw):
    return max(1, div_int(mul(g_med, hw), 16))


def fields(seed, n, t):
    K = keys_for(seed)
    cx, cy = continent_centre(seed, t)
    N2 = n * n
    c = [0] * N2
    nb = [0] * N2
    ns = [0] * N2
    for y in range(n):
        for x in range(n):
            i = y * n + x
            c[i], nb[i], ns[i] = e2_cell(x, y, n, t, K, cx, cy)
    c_sea = coast_threshold(c, t["land_fraction"])
    g = belt_gradient(n, nb)
    g_med = max(1, kth(g, quantile_rank(HALF, N2)))
    hw = derived(t, n)["hw"]
    w_b = belt_width(g_med, hw)
    s_land = land_scale(c, c_sea)
    return {"c": c, "nb": nb, "ns": ns, "c_sea": c_sea, "w_b": w_b, "s_land": s_land,
            "g_med": g_med, "cx": cx, "cy": cy}


