def quantize(hgrid, ocean):
    out = []
    for i, hv in enumerate(hgrid):
        q = mul_div(hv, 10, 1 << 32)
        out.append(min(-1, q) if ocean[i] else max(1, q))
    return out


def cost_bump(seed, w, h, t, ocean):
    K = keys_for(seed)
    n = w * h
    cost = [ONE] * n
    bump = [0] * n
    for i in range(n):
        if ocean[i]:
            continue
        x, y = i % w, i // w
        X = from_int(16 * x + 8)
        Y = from_int(16 * y + 8)
        nz = fbm_m(K["fill"], X, Y, t["fill_noise"])
        cost[i] = add(ONE, mul(t["fill_cost_amp"], clamp(HALF + nz, 0, ONE)))
        dn = fbm_m(K["detail"], X, Y, t["detail_noise"])
        bv = mul(t["fill_detail_m"], max(0, dn))
        bump[i] = mul_div(bv, 10 * (1 << 16), 1 << 32)
    return cost, bump


def condition(w, h, e, ocean, cost, bump, lake_min, lake_max, min_depth, max_share, fine_slope, info=None):
    n = w * h
    k = list(e)
    L, parent, order = g3_flood(w, h, k, ocean)
    depressed = bytearray(1 if (not ocean[i] and L[i] > k[i]) else 0 for i in range(n))
    label, comps = g2_components(w, h, depressed, 8, L)
    stats = []
    for lab, cells in enumerate(comps, 1):
        depth = max(L[c] - k[c] for c in cells)
        vol = sum(L[c] - k[c] for c in cells)
        stats.append((lab, len(cells), depth, vol, cells))
    cands = [s for s in stats if lake_min <= s[1] <= lake_max and s[2] >= min_depth]
    cands.sort(key=lambda s: (-s[3], s[0]))
    kept = bytearray(n)
    total = 0
    kept_labels = []
    for s in cands:
        if total + s[1] > max_share:
            continue
        for c in s[4]:
            kept[c] = 1
        total += s[1]
        kept_labels.append(s[0])
    # E10.4
    tab = nbt(w, h)
    visited = bytearray(n)
    kf = [0] * n
    P = [0] * n
    heap = []
    seq = 0
    for i in range(n):
        if ocean[i]:
            visited[i] = 1
            heap.append((0, seq, i))
            seq += 1
    if not heap:
        fatal("E10: no ocean")
    heapq.heapify(heap)
    pops = []
    while heap:
        lv, _, c = heapq.heappop(heap)
        pops.append(c)
        for code, m in tab[c]:
            if visited[m]:
                continue
            visited[m] = 1
            base = checked(k[m] * FINE)
            if kept[m]:
                kf[m] = base
                P[m] = max(base, lv)
            else:
                ce = mul(cost[m], SQRT2) if code & 1 else cost[m]
                eps = max(1, mul_div(fine_slope, ce, 1 << 32)) if depressed[m] else 1
                if depressed[m] or (k[m] == 1 and base <= lv):
                    eps = checked(eps + bump[m])
                kf[m] = max(base, checked(lv + eps))
                P[m] = kf[m]
            heapq.heappush(heap, (P[m], seq, m))
            seq += 1
    out = [0] * n
    for i in range(n):
        if ocean[i] or kept[i]:
            out[i] = k[i]
        else:
            out[i] = min(KEY_MAX, kf[i] >> 16)
    if info is not None:
        info["L"] = L
        info["stats"] = [(s[0], s[1], s[2], s[3]) for s in stats]
        info["candidates"] = [s[0] for s in cands]
        info["kept_labels"] = kept_labels
        info["kept_cells"] = total
        info["kf"] = kf
        info["pops"] = pops
    return out


