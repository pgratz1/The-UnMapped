def _pack(fmt, values):
    a = array(fmt, values)
    if sys.byteorder != "little":
        a.byteswap()
    return a.tobytes()


def h_i64(values):
    return hashlib.sha256(_pack("q", values)).hexdigest()


def h_u8(values):
    return hashlib.sha256(bytes(values)).hexdigest()


def h_i16(values):
    return hashlib.sha256(_pack("h", values)).hexdigest()


def layer_hash(n, values):
    head = n.to_bytes(4, "little") + n.to_bytes(4, "little") + bytes([4])
    return hashlib.sha256(head + _pack("h", values)).hexdigest()


