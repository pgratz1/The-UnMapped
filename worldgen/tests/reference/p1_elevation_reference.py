def rc(a, b):
    if a >= mul_int(b, RATIO_CAP):
        return from_int(RATIO_CAP)
    return div(a, b)


def coast_tl(c, c_sea, s_land):
    s = sub(c, c_sea)
    return rc(abs(s), s_land)


def gm_of(tl, mountain_coast_t):
    return fade(clamp(div(tl, mountain_coast_t), 0, ONE))


def belt_profile(nb, o, w_b):
    a = abs(sub(nb, o))
    if a >= w_b:
        return 0
    return fade(ONE - div(a, w_b))


def seg_profile(ns, beta, contrast):
    return fade(clamp(add(add(HALF, beta), mul(contrast, ns)), 0, ONE))


def mask_of(nb, ns, gm, o, beta, w_b, contrast):
    return mul(mul(belt_profile(nb, o, w_b), seg_profile(ns, beta, contrast)), gm)


def floor_search(nbs, nss, gms, w_b, t, trace=None):
    """E5.1 on lists of the land cells' nb, ns, gm. Returns a dict."""
    L_O = len(nbs)
    target = round_int(mul(from_int(L_O), t["segment_on_share"]))
    lev = t["segment_floor_mask"]
    inland = t["floor_inland_gm"]
    contrast = t["segment_contrast"]
    bias = t["segment_bias"]
    two = from_int(2)
    cells = list(zip(nbs, nss, gms))

    def core(o, beta):
        return sum(1 for (b, s, g) in cells if mask_of(b, s, g, o, beta, w_b, contrast) >= lev)

    def inl(o, beta):
        return sum(1 for (b, s, g) in cells if g >= inland and mask_of(b, s, g, o, beta, w_b, contrast) >= lev)

    res = {"target": target, "triggered": False, "o": 0, "beta": bias, "mids": [], "offsets": []}
    if core(0, bias) >= target:
        return res
    res["triggered"] = True
    d = div_int(w_b, 2)
    best_o = 0
    best_r = inl(0, two)
    res["offsets"].append((0, best_r))
    if best_r < target:
        done = False
        for s in range(1, t["belt_offset_steps"] + 1):
            for sign in (1, -1):
                o = mul_int(d, sign * s)
                r = inl(o, two)
                res["offsets"].append((o, r))
                if r > best_r:
                    best_r = r
                    best_o = o
                if r >= target:
                    done = True
                    break
            if done:
                break
    o_star = best_o
    lo = bias
    hi = two
    if core(o_star, lo) >= target:
        hi = lo
    else:
        for _ in range(32):
            mid = (lo + hi) >> 1
            cm = core(o_star, mid)
            res["mids"].append((mid, cm, lo, hi))
            if cm >= target:
                hi = mid
            else:
                lo = mid
    res["o"] = o_star
    res["beta"] = hi
    return res


def floor_for_world(n, t, f, O):
    c_sea, s_land = f["c_sea"], f["s_land"]
    nbs, nss, gms = [], [], []
    for i in range(n * n):
        if O[i]:
            continue
        tl = coast_tl(f["c"][i], c_sea, s_land)
        nbs.append(f["nb"][i])
        nss.append(f["ns"][i])
        gms.append(gm_of(tl, t["mountain_coast_t"]))
    return floor_search(nbs, nss, gms, f["w_b"], t)


