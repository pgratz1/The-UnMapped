GOLDEN = 0x9E3779B97F4A7C15
TAG_CELL2 = cr.TAG_CELL2


def _mix64(z):
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return z ^ (z >> 31)


def hash_at(key, x, y):
    h = _mix64(((TAG_CELL2 ^ key) + GOLDEN) & M64)
    h = _mix64(((h ^ (x & M64)) + GOLDEN) & M64)
    h = _mix64(((h ^ (y & M64)) + GOLDEN) & M64)
    return _mix64(((h ^ 3) + GOLDEN) & M64)


