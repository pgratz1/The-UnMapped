def run_world(seed, n, t, upto=None):
    """Every intermediate of one world, as a dict."""
    r = {"seed": seed, "n": n}
    f = fields(seed, n, t)
    r["fields"] = f
    O = classify(n, t, f)
    r["O"] = O
    L_O = n * n - sum(O)
    r["L_O"] = L_O
    hts = heights(seed, n, t, f, O)
    r["heights"] = hts
    if upto == "heights":
        return r
    d = derived(t, n)
    p = erosion_params(t, stream_key(seed, "geo.elevation.erosion"))
    h8 = erode(n, n, hts["h7"], O, p)
    r["h8"] = h8
    e = quantize(h8, O)
    r["e"] = e
    cost, bump = cost_bump(seed, n, n, t, O)
    max_share = max(1, round_int(mul(from_int(L_O), t["lake_max_share"])))
    r["max_share"] = max_share
    info = {}
    ef = condition(n, n, e, O, cost, bump, d["lake_min_cells"], d["lake_max_cells"],
                   d["lake_min_depth_dm"], max_share, d["fine_slope"], info)
    r["e_final"] = ef
    r["info"] = info
    return r


