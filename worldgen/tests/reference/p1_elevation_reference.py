def chk(r):
    if r > RAW_MAX or r < -RAW_MAX:
        fatal("Fx overflow")
    return r


def add(a, b):
    r = a + b
    if r > RAW_MAX or r < -RAW_MAX:
        fatal("Fx add overflow")
    return r


def sub(a, b):
    r = a - b
    if r > RAW_MAX or r < -RAW_MAX:
        fatal("Fx sub overflow")
    return r


def mul(a, b):
    p = a * b
    if p >= 0:
        q = (p + HALF) >> 32
    else:
        q = -((HALF - p) >> 32)
    if q > RAW_MAX or q < -RAW_MAX:
        fatal("mul overflow")
    return q


def rha(n, d):
    if d == 0:
        fatal("division by zero")
    an = -n if n < 0 else n
    ad = -d if d < 0 else d
    q, r = divmod(an, ad)
    if 2 * r >= ad:
        q += 1
    return -q if (n < 0) != (d < 0) else q


def div(a, b):
    if b == 0:
        fatal("div by zero")
    return chk(rha(a << 32 if a >= 0 else -((-a) << 32), b))


def mul_int(a, n):
    return chk(a * n)


def div_int(a, n):
    return chk(rha(a, n))


def mul_div(a, b, c):
    r = rha(a * b, c)
    if r > RAW_MAX or r < -RAW_MAX:
        fatal("mul_div overflow")
    return r


def from_int(n):
    if n < -(2 ** 31 - 1) or n > 2 ** 31 - 1:
        fatal("from_int range")
    return n << 32


def from_ratio(num, den):
    return chk(rha(num * ONE, den))


def round_int(a):
    return rha(a, ONE)


def clamp(x, lo, hi):
    if lo > hi:
        fatal("clamp")
    return lo if x < lo else hi if x > hi else x


def fade(t):
    if t < 0 or t > ONE:
        fatal("fade out of range")
    t2 = mul(t, t)
    t3 = mul(t2, t)
    a = 6 * t - 15 * ONE
    b = add(mul(t, a), 10 * ONE)
    f = mul(t3, b)
    return 0 if f < 0 else ONE if f > ONE else f


