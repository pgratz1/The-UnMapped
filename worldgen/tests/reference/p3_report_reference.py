def esc(s):
    out = []
    for ch in s:
        b = ord(ch)
        if b == 0x5C:
            out.append("\\\\")
        elif b < 0x20 or b >= 0x7F:
            out.append("\\x%02X" % b)
        else:
            out.append(ch)
    return "".join(out)


def finish(line):
    """Escape (R4), then write each trailing space as \\x20."""
    s = esc(line)
    n = len(s) - len(s.rstrip(" "))
    return s[:len(s) - n] + "\\x20" * n if n else s


def pl(n, w):
    return "%d %s" % (n, w if n == 1 else w + "s")


def span(e):
    return "%d" % e[1] if e[2] == e[1] else "%d-%d" % (e[1], e[2])


def standing(status):
    return status in (1, 2)


