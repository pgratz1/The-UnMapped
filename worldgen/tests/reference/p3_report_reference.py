def ruin_how(w, eid):
    """25.3 item 1: the <how> of a ruin event."""
    k = w.kind_key[w.ev[eid][3]]
    if k == "sacked":
        by = role_ids(w, eid, "attacker")
        return "sacked by %s" % w.ref(CIV, by[0]) if by else "sacked"
    if k == "settlement_abandoned":
        return "abandoned"
    if k == "settlement_abandoned_to":
        dest = role_ids(w, eid, "destination")
        return "abandoned, survivors to %s" % w.ref(SETTLEMENT, dest[0]) if dest else "abandoned"
    return k


def standing_claims(w):
    claim_k = kset(w, ("claim", "claim_settlements"))
    decl = w.K["war_declared"]
    pursued = {c for e in w.t["event"] if e[3] == decl for c in w.causes.get(e[0], [])}
    if V2:   # 25.9 item 2, test (iv): a claim caused into a claim_dropped is closed
        pursued |= {c for e in w.t["event"] if e[3] == w.K["claim_dropped"] for c in w.causes.get(e[0], [])}
    decls = [(e[1], frozenset(role_ids(w, e[0], "attacker") + role_ids(w, e[0], "defender")))
             for e in w.t["event"] if e[3] == decl]
    claims = [e for e in w.t["event"] if e[3] in claim_k]
    out = []
    for e in claims:
        if e[0] in pursued:
            continue
        a, b = role_ids(w, e[0], "claimant")[0], role_ids(w, e[0], "holder")[0]
        if w.civ[a][8] is not None or w.civ[b][8] is not None:
            continue
        if any(y >= e[1] and pair == frozenset((a, b)) for y, pair in decls):
            continue
        if any(x[0] > e[0] and role_ids(w, x[0], "claimant") == [a] and role_ids(w, x[0], "holder") == [b]
               for x in claims):
            continue
        out.append(e[0])
    return out


