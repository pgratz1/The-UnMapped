def stats(w, d):
    t, E, K = w.t, w.E, w.K
    o = []
    ph = t["phase"]

    def years(kinds):
        return sum(p[4] - p[3] + 1 for p in ph if p[2] in kinds)

    sim = years((1, 3, 4))
    o += [("end_year", E), ("ages", len(t["age"])), ("phases", len(ph))]
    for k, nm in ((1, "opening"), (2, "quiet"), (3, "flare"), (4, "final")):
        o.append(("phases_" + nm, sum(1 for p in ph if p[2] == k)))
    o += [("simulated_years", sim), ("simulated_permille", 1000 * sim // E), ("quiet_years", years((2,))),
          ("flare_years", years((3,))), ("events", len(t["event"]))]
    by_kind = {}
    for e in t["event"]:
        by_kind[e[3]] = by_kind.get(e[3], 0) + 1
    for k in t["event_kind"]:
        o.append(("events_" + k[1], by_kind.get(k[0], 0)))
    o += [("events_caused", len(w.causes)), ("cause_links", len(t["event_cause"])),
          ("events_per_1000_simulated_years", 1000 * len(t["event"]) // sim if sim else 0),
          ("summary_threshold", d.T), ("summary_events", len(d.shown))]
    civs = t["civilization"]
    o += [("civilizations", len(civs)), ("civilizations_alive", sum(1 for c in civs if c[8] is None)),
          ("civilizations_ended", sum(1 for c in civs if c[8] is not None))]
    for r in t["race"]:
        o.append(("civilizations_" + r[1], sum(1 for c in civs if c[2] == r[0])))
    o.append(("civ_lifetime_max", max([(c[8] if c[8] is not None else E) - c[6] for c in civs] or [0])))
