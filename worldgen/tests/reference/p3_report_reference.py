    def _bind(self):
        """Points p3_conflict_reference's kind ids at this world's stored catalogue."""
        pcr.K = self.K
        pcr.CLAIMS = (self.K["claim"], self.K["claim_settlements"])
        pcr.CEDES = (self.K["region_ceded"], self.K["settlements_ceded"])

    def sentence(self, eid):
        s = self._sentences.get(eid)
        if s is None:
            s = pe.render(self.view, eid)
            self._sentences[eid] = s
        return s

    # names and references (6.1 "Ids")
    def name(self, typ, i):
        if typ == RACE:
            return self.race[i][2]
        if typ == GOD:
            return self.god[i][1]
        if typ == CIV:
            return self.civ[i][1]
        if typ == SETTLEMENT:
            return self.settlement[i][1]
        if typ == REGION:
            return self.region[i][1]
        return None

    def ref(self, typ, i):
        n = self.name(typ, i)
        if n is None:
            return "%s%d" % (PREFIX[typ], i)
        return "%s (%s%d)" % (n, PREFIX[typ], i)


