    order = sorted(by, key=lambda o_: (min(x[5] for x in by[o_]), o_[0], o_[1]))
    out = ["  adversaries: %d" % len(order)]
    no_war = [0, 0]   # 25.4: (m, e)
    for o_ in order:
        rows = by[o_]
        ref = w.ref(o_[0], o_[1])
