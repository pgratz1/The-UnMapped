        self.inp = Inputs(self)
        self.view = pe.view_from_rows(self.res, [(r[0], r[1]) for r in t["region"]], t["race"], t["god"])
        self._bind()
        self.idx = pcr._index(self.res)
        self._sentences = {}
        self.civ_events = {}
        for p in t["event_participant"]:
            if p[3] == CIV:
                lst = self.civ_events.setdefault(p[4], [])
