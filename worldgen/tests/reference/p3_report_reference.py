def war_of(w):
    """24.1: war(e) for every event, in one pass in id order (None for none)."""
    W, EW, decl = kset(w, W_KINDS), kset(w, EW_KINDS), w.K["war_declared"]
    ended_by = {}
    for r in w.t["relation"]:
        if r[4] == "war" and r[6] is not None:
            u = r[8]
            ended_by[u] = min(ended_by.get(u, r[7]), r[7])
    war = {}
    for e in w.t["event"]:
        eid, k = e[0], e[3]
        if k == decl:
            war[eid] = eid
        elif k in EW and any(w.ev[c][3] in W for c in w.causes.get(eid, [])):
            c = min(c for c in w.causes.get(eid, []) if w.ev[c][3] in W)
            war[eid] = war.get(c)
        elif k in EW and eid in ended_by:
            war[eid] = ended_by[eid]
        else:
            war[eid] = None
    return war


class Frames:
    """24.1 frames and 24.2 units over one world."""

    def __init__(self, w):
        self.w = w
        self.war = war_of(w)
        battles = kset(w, ("battle", "battle_at_pass", "allied_battle", "battle_led"))   # P5-04 11.1, P5-06 11.1
        self.last_battle = {}
        for e in w.t["event"]:
            d = self.war[e[0]]
            if e[3] in battles and d is not None:
                self.last_battle[d] = max(self.last_battle.get(d, 0), e[0])
        self.row = {r[7]: r for r in w.t["relation"] if r[4] == "war"}
        kids = {}
        for e, cs in w.causes.items():
            for c in cs:
                kids.setdefault(c, []).append(e)
        self.kids = kids
        cost = kset(w, ("region_ceded", "settlements_ceded", "tribute"))
        search = w.K["search_abandoned"]
        self.excluded = set()       # 22.5a
        self.frame = {}
        for d in (e[0] for e in w.t["event"] if e[3] == w.K["war_declared"]):
            r = self.row.get(d)
            u = r[8] if r is not None and r[6] is not None else None
            if u is not None and w.ev[u][3] == search and w.ev[u][7] < SUMMARY_MIN_SALIENCE:
                self.excluded.add(d)
                self.frame[d] = set()
                continue
            f = {d}
            if d in self.last_battle:
                f.add(self.last_battle[d])
                if V8:   # P5-06 10.3: a general's fall is a companion of the battle it cites, shown as the war's last
                    f |= {x for x in kids.get(self.last_battle[d], []) if w.ev[x][3] == w.K["fell_in_battle"]}
            if u is not None:
                f.add(u)
                f |= {x for x in kids.get(u, []) if w.ev[x][3] in cost}
            self.frame[d] = f
        self.conseq = kset(w, ("capital_moved", "refugees_settled", "civ_conquered"))
        self.falls = kset(w, ("sacked", "settlement_captured"))

    def unit(self, eid):
        w = self.w
        out = set(pcr.unit(w.res, eid, w.idx))          # parts 1 and 2 (21.2, 21.8, 23 item 2)
        d = self.war.get(eid)
        if d is not None:
            out |= self.frame.get(d, set())               # part 3
        if w.ev[eid][3] in self.conseq:                   # part 4
            cs = sorted(c for c in w.causes.get(eid, []) if w.ev[c][3] in self.falls)
            if cs:
                out.add(cs[0])
        if V7:   # P5-04 10.3: the companions of alliances
            K, k = w.K, w.ev[eid][3]
            calls = kset(w, ("ally_joined_war", "ally_refused", "alliance_betrayed"))
            ends = kset(w, ("peace", "war_won", "civ_conquered"))   # the endings that owe spoils (6.11 ruling)
            spoils = kset(w, ("spoils_shared", "spoils_withheld"))
            if k == K["war_declared"]:
                out |= {x for x in self.kids.get(eid, []) if w.ev[x][3] in calls}
            if k in ends:
                out |= {x for x in self.kids.get(eid, []) if w.ev[x][3] in spoils}
            if k == K["alliance_betrayed"]:
                out |= {c for c in w.causes.get(eid, []) if w.ev[c][3] == K["war_declared"]}
        if V11:   # P5-08 12.1 item 1: the ally_aided_hold events citing an outcome are companions in its unit
            K, k = w.K, w.ev[eid][3]
            if k in kset(w, ("deep_sealed", "warren_sealed", "hold_lost")):
                out |= {x for x in self.kids.get(eid, []) if w.ev[x][3] == K["ally_aided_hold"]}
        if V8:   # P5-06 10.3: a disputed succession with the crisis and the secession it cites, the exile with it
            K, k = w.K, w.ev[eid][3]
            exiles = lambda x: {y for y in self.kids.get(x, []) if w.ev[y][3] == K["exiled"]}  # noqa: E731
            if k in (K["succession_crisis"], K["civ_seceded"]):
                for x in self.kids.get(eid, []):
                    if w.ev[x][3] == K["succession_disputed"]:
                        out |= {x} | exiles(x)
            elif k == K["succession_disputed"]:
                out |= exiles(eid)
        return out


