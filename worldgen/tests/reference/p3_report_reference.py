def ruin_how(w, eid, s=None):
    """25.3 item 1: the <how> of a ruin event; P5-02 12.3: an overrun, and ` after plague` or ` after famine`
    after `abandoned` when the settlement's ending is 3 or 4."""
    k = w.kind_key[w.ev[eid][3]]
    if k == "sacked":
        by = role_ids(w, eid, "attacker")
        return "sacked by %s" % w.ref(CIV, by[0]) if by else "sacked"
    after = ""
    if V4 and s is not None and len(s) > 14:
        after = {3: " after plague", 4: " after famine"}.get(s[14], "")
    if V5 and s is not None and len(s) > 14 and s[14] == 6:   # P5-03 11.3: the monster of the cause
        fk = w.K["settlement_fled"]
        fl = [c for c in w.causes.get(eid, []) if w.ev[c][3] == fk]
        m = role_ids(w, fl[0], "monster") if fl else []
        after = " for fear of %s" % w.ref(MONSTER, m[0]) if m else ""
    if k == "settlement_abandoned":
        return "abandoned" + after
    if k == "settlement_abandoned_to":
        dest = role_ids(w, eid, "destination")
        return "abandoned%s, survivors to %s" % (after, w.ref(SETTLEMENT, dest[0])) if dest else "abandoned" + after
    if V4 and k == "settlement_overrun":
        m = role_ids(w, eid, "monster")
        return "overrun by %s" % w.ref(MONSTER, m[0]) if m else "overrun"
    if V10 and k == "hold_lost":   # P5-07 10 item 4
        m = role_ids(w, eid, "monster")
        return "lost to %s" % w.ref(MONSTER, m[0]) if m else "lost"
    return k


def standing_claims(w):
    claim_k = kset(w, ("claim", "claim_settlements"))
    decl = w.K["war_declared"]
    pursued = {c for e in w.t["event"] if e[3] == decl for c in w.causes.get(e[0], [])}
    if V2:   # 25.9 item 2, test (iv): a claim caused into a claim_dropped is closed
        pursued |= {c for e in w.t["event"] if e[3] == w.K["claim_dropped"] for c in w.causes.get(e[0], [])}
    decls = [(e[1], frozenset(role_ids(w, e[0], "attacker") + role_ids(w, e[0], "defender")))
             for e in w.t["event"] if e[3] == decl]
    claims = [e for e in w.t["event"] if e[3] in claim_k]
    out = []
    for e in claims:
        if e[0] in pursued:
            continue
        a, b = role_ids(w, e[0], "claimant")[0], role_ids(w, e[0], "holder")[0]
        if w.civ[a][8] is not None or w.civ[b][8] is not None:
            continue
        if any(y >= e[1] and pair == frozenset((a, b)) for y, pair in decls):
            continue
        if any(x[0] > e[0] and role_ids(w, x[0], "claimant") == [a] and role_ids(w, x[0], "holder") == [b]
               for x in claims):
            continue
        out.append(e[0])
    return out


