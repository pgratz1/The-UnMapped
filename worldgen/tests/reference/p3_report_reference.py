def note(w, eid, civ=0):
    """history_note(view, eid[, civ]) without its parentheses, or ""."""
    e = w.ev[eid]
    k = e[3]
    if k == w.K["war_declared"]:
        cl = sorted(c for c in w.causes.get(eid, []) if w.ev[c][3] in (w.K["claim"], w.K["claim_settlements"]))
        if not cl:
            return ""
        c = w.ev[cl[0]]
        yc = c[1]
        if c[3] == w.K["claim_settlements"]:
            # 23 item 4a: the towns of the claim, in participant order, and the claim's region
            role = [r[1] for r in w.roles[c[3]] if r[2] == "settlement"][0]
            ss = [pcr.mid(w.name(SETTLEMENT, p[4])) for p in sorted(w.parts.get(c[0], [])) if p[2] == role]
            where = "%s in %s" % (pe.join_all(ss), pcr.mid(w.name(REGION, c[5])))
            text = ("The claim, since %d, was to %s." % (yc, where) if yc < e[1] else
                    "The claim, made the same year, was to %s." % where)
        elif c[5] != e[5]:
            rc = pcr.mid(w.name(REGION, c[5]))      # 23 item 3
            text = ("The claim, since %d, was to %s." % (yc, rc) if yc < e[1] else
                    "The claim, made the same year, was to %s." % rc)
        else:
            text = "Claimed since %d." % yc if yc < e[1] else "Claimed the same year."
        n = w.war_n[eid]
        if n >= 2:
            text += " The %s war between them." % pcr.ordinal(n)
        return text
    if k == w.K["flare_up"]:
        return pcr.history_note(w.res, w.inp, eid, w.view, w.idx)
    if k == w.K["quiet_stretch"] and civ and any(p[3] == CIV and p[4] == civ for p in w.parts.get(eid, [])):
        c = w.civ[civ]
        g = w.race[c[2]][7]
        n = (e[2] + 1 - c[6]) // g - (e[1] - c[6]) // g
        if n == 0:
            tail = "no new generation of rulers."
        elif n == 1:
            tail = "one new generation of rulers."
        else:
            tail = "%d new generations of rulers." % n
        return "%s: %s" % (c[1], tail)
    return ""


def with_note(sentence, nt):
    return sentence + (" (%s)" % nt if nt else "")


