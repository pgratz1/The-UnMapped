def cmd_check(argv):
    inputs = argv[argv.index("--inputs") + 1] if "--inputs" in argv else DEFAULT_INPUTS
    c = Checker()
    check_fixture_facts(c)
    if V2:
        check_fixture_facts_v2(c)
    for name in fixture_names():
        check_invariants(c, name, load_world(fixture_db(name)))
    have = all(os.path.exists(os.path.join(inputs, n + ".db")) for n in WORLD_CASES)
    if have:
        for name in WORLD_CASES:
            check_invariants(c, name, load_world(os.path.join(inputs, name + ".db")))
        if os.path.exists(GOLDEN):
            with open(GOLDEN) as f:
                c.eq("golden file is current", f.read(), golden_text(inputs))
        else:
            c.eq("golden file exists", False, True)
    else:
        print("note: %s lacks the world cases; world invariants and the golden comparison are skipped" % inputs)
    print("%d checks, %d failures" % (c.count, c.failures))
    return 1 if c.failures else 0


def cmd_report(argv):
    path = argv[0]
    level = argv[argv.index("--level") + 1] if "--level" in argv else "summary"
    try:
        text = report(load_world(path), level)
    except ReportError as e:
        sys.stderr.write("worldgen-cli: error: %s\n" % (e.message.replace("%s", path, 1)
                                                         if "%s" in e.message else e.message))
        return e.code
    if "--out" in argv:
        with open(argv[argv.index("--out") + 1], "wb") as f:
            f.write(text)
    else:
        sys.stdout.buffer.write(text)
    return 0


def build_input(src, dst):
    """P5-01 (0.21.0) golden inputs from a 0.20.0 world written by the C++: table region renamed by P1-06 r10
    (p1_regions_reference.rename_db), the five chronology tables and the thirteen history tables recomputed by the
    chronology and conflict references (shipped data of the checkout), meta generator_version 0.21.0 and
    content_hash that of game/data (p3_data_reference). Every other table and meta row is the source's."""
    import shutil
    import p1_regions_reference as p1r
    tmp = dst + ".tmp"
    shutil.copyfile(src, tmp)
    p1r.rename_db(src, tmp)
    conn = pchr.open_world(tmp)
    meta = dict(conn.execute("SELECT key, value FROM meta").fetchall())
    p = pchr.params_from_meta(meta)
    dat = pcr.data(os.path.join(REPO, "game", "data"))
    inp, chron = pcr.inputs_for(dat, conn, p, int(meta["seed"]), int(meta["param.map_size"]))
    conn.close()
    res = pcr.history_stage(dat, inp)
    c = sqlite3.connect(tmp)
    try:
        for t in pchr.TABLES:
            c.execute('DELETE FROM "%s"' % t)
            n = pchr.COLUMNS[t]
            c.executemany('INSERT INTO "%s" VALUES (%s)' % (t, ",".join("?" * n)), [tuple(r) for r in chron[t]])
        for t in pcr.TABLES:
            c.execute('DELETE FROM "%s"' % t)
            n = pcr.COLUMNS[t]
            c.executemany('INSERT INTO "%s" VALUES (%s)' % (t, ",".join("?" * n)), [tuple(r) for r in res[t]])
        c.execute("UPDATE meta SET value = ? WHERE key = 'generator_version'", (GENERATOR_VERSION,))
        c.execute("UPDATE meta SET value = ? WHERE key = 'content_hash'",
                  (pcr.pdr.content_hash(os.path.join(REPO, "game", "data")),))
        c.commit()
    finally:
        c.close()
    os.replace(tmp, dst)
    return len(res["event"])


def cmd_build_inputs(argv):
    src_dir, dst_dir = argv[0], argv[1]
    names = [a for a in argv[2:] if not a.startswith("--")] or list(WORLD_CASES)
    os.makedirs(dst_dir, exist_ok=True)
    for name in names:
        n = build_input(os.path.join(src_dir, name + ".db"), os.path.join(dst_dir, name + ".db"))
        print("%s: %d events" % (name, n))
        sys.stdout.flush()
    return 0


def cmd_compare(argv):
    w = load_world(argv[0])
    bad = 0
    for level, path in (("summary", argv[1]), ("full", argv[2])):
        with open(path, "rb") as f:
            got = f.read()
        want = report(w, level)
        if got != want:
            bad = 1
            g, x = got.split(b"\n"), want.split(b"\n")
            for i in range(max(len(g), len(x))):
                a = g[i] if i < len(g) else b"<missing>"
                b = x[i] if i < len(x) else b"<missing>"
                if a != b:
                    print("%s %s line %d:\n  C++       %s\n  reference %s" % (argv[0], level, i + 1, a.decode("latin-1"),
                                                                            b.decode("latin-1")))
                    break
    if not bad:
        print("%s: equal at both levels" % argv[0])
    return bad


def cmd_metrics(argv):
    """24.11 item 2: per world, the summary's T, shown, shown declarations and orphans."""
    for path in argv:
        w = load_world(path)
        d = Digest(w)
        decl = sum(1 for x in d.shown if w.ev[x][3] == w.K["war_declared"])
        print("%s T %d shown %d declarations %d orphans %d" % (os.path.basename(path), d.T, len(d.shown), decl,
                                                               orphans(w, d.frames, d.shown)))
    return 0


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    if "--version" in argv:
        i = argv.index("--version")
        use_version(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    cmd, rest = argv[0], argv[1:]
    if cmd == "report":
        return cmd_report(rest)
    if cmd == "fixture":
        write_fixture(rest[0], rest[1])
        return 0
    if cmd == "hashes":
        for t, h in detail_tables(rest[0]):
            print("table %s %s" % (t, h))
        return 0
    if cmd == "golden":
        inputs = rest[rest.index("--inputs") + 1] if "--inputs" in rest else DEFAULT_INPUTS
        text = golden_text(inputs)
        path = rest[0] if rest and not rest[0].startswith("--") else GOLDEN
        if path == "-":
            sys.stdout.write(text)
        else:
            with open(path, "w", newline="\n") as f:
                f.write(text)
        return 0
    if cmd == "compare":
        return cmd_compare(rest)
    if cmd == "build-inputs":
        return cmd_build_inputs(rest)
    if cmd == "check":
        return cmd_check(rest)
    if cmd == "metrics":
        return cmd_metrics(rest)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
