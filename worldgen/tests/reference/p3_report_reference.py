def _latin1(b):
    return b.decode("latin-1")


def connect(path):
    conn = sqlite3.connect("file:%s?mode=ro&immutable=1" % path, uri=True)
    conn.text_factory = _latin1
    return conn


def pk_rows(conn, table):
    info = conn.execute("SELECT name, pk FROM pragma_table_info(?) ORDER BY cid", (table,)).fetchall()
    cols = [r[0] for r in info]
    pks = [r[0] for r in sorted((r for r in info if r[1] > 0), key=lambda r: r[1])]
    order = ", ".join('"%s" COLLATE BINARY' % p for p in pks)
    return cols, conn.execute('SELECT %s FROM "%s" ORDER BY %s' % (", ".join('"%s"' % c for c in cols), table,
                                                                   order)).fetchall()


