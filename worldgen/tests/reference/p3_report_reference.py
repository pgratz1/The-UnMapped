def held_series(w, civs, only_nonislet=False):
    """7.1: held(c, Y) for Y in [0, E - 1], per civilization."""
    E = w.E
    diffs = {c: [0] * (E + 1) for c in civs}
    for r in w.t["region_control"]:
        if only_nonislet and is_islet(w.region[r[0]]):
            continue
        d = diffs.get(r[3])
        if d is None:
            continue
        d[r[1]] += 1
        d[r[2] if r[2] is not None else E] -= 1
    out = {}
    for c, d in diffs.items():
        s, run = [0] * E, 0
        for y in range(E):
            run += d[y]
            s[y] = run
        out[c] = s
    return out


def peak_run(series):
    m = max(series) if series else 0
    if m == 0:
        return (0, 0, 0)
    a = series.index(m)
    b = a
    while b + 1 < len(series) and series[b + 1] == m:
        b += 1
    return (m, a, b)


def population_peaks(w):
    """7.2: civilization -> (P, year), over the census years."""
    rows = sorted(w.t["settlement_census"], key=lambda r: (r[1], r[0]))
    state, pop, best = {}, {}, {}
    i = 0
    while i < len(rows):
        y = rows[i][1]
        changed = set()
        while i < len(rows) and rows[i][1] == y:
            s, _y, owner, _k, status, p = rows[i]
            old = state.get(s)
            if old is not None and standing(old[4]) and old[2]:
                pop[old[2]] -= old[5]
                changed.add(old[2])
            if standing(status) and owner:
                pop[owner] = pop.get(owner, 0) + p
                changed.add(owner)
            state[s] = rows[i]
            i += 1
        for c in sorted(changed):
            if pop[c] > best.get(c, (0, 0))[0]:
                best[c] = (pop[c], y)
    return best


def is_islet(region):
    return region[RC["cells"]] - region[RC["lake_cells"]] < ISLET_MAX_DRY_CELLS


def milestones(w, c):
    ev = w.civ_events.get(c, [])
    top = sorted(ev, key=lambda x: (-w.ev[x][7], x))[:MILESTONES]
    return sorted(top)


class Digest:
    def __init__(self, w):
        self.w = w
        civs = [c[0] for c in w.t["civilization"]]
        held = held_series(w, civs)
        self.peak_regions = {c: peak_run(held[c]) for c in civs}
        self.peak_pop = population_peaks(w)
        st = w.t["settlement"]
        self.founded = {c: sum(1 for s in st if s[5] == c) for c in civs}
        self.held_settlements = {c: sum(1 for s in st if s[8] == c and standing(s[10])) for c in civs}
        self.ruined = {c: sum(1 for s in st if s[5] == c and s[10] in (3, 4)) for c in civs}
        self.population = {c: sum(s[11] for s in st if s[8] == c and standing(s[10])) for c in civs}
        self.regions_held = {c: sum(1 for r in w.t["region_control"] if r[3] == c and r[2] is None) for c in civs}
        T, shown, _per_age = pcr.summary_set(w.res, w.inp)
        self.T, self.shown = T, shown
        # 7.5
        self.N = sum(1 for r in w.t["region"] if not is_islet(r))
        self.shares = {}
        if self.N > 0:
            h = held_series(w, civs, only_nonislet=True)
            self.shares = {c: [1000 * x // self.N for x in h[c]] for c in civs}


