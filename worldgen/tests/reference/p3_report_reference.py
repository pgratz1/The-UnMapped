    o.append(("civ_population_peak_max", max([d.peak_pop.get(c[0], (0, 0))[0] for c in civs] or [0])))
    st = t["settlement"]
    stand = [s for s in st if standing(s[10])]
    o += [("settlements", len(st)), ("settlements_standing", len(stand))]
    for k, nm in ((1, "thriving"), (2, "declining"), (3, "ruined"), (4, "faded")):
        o.append(("settlements_" + nm, sum(1 for s in st if s[10] == k)))
    for k in range(1, 6):
        o.append(("settlements_" + SKIND[k], sum(1 for s in st if s[9] == k)))
    o += [("settlements_unowned", sum(1 for s in stand if s[8] == 0)), ("population", sum(s[11] for s in stand)),
          ("population_settlement_max", max([s[11] for s in stand] or [0])),
          ("census_rows", len(t["settlement_census"])), ("regions", len(t["region"])), ("regions_nonislet", d.N)]
    rc = t["region_control"]
    held_open = [r for r in rc if r[2] is None]
    o += [("regions_held", len(held_open)), ("region_control_rows", len(rc)),
          ("regions_ever_held", len({r[0] for r in rc}))]
    best = (0, 0, 0)  # (share, Y, c); ties: smallest Y, then smallest c
    if d.N > 0:
        for c in sorted(d.shares):
            s = d.shares[c]
            mx = max(s) if s else 0
            if mx == 0:
                continue
            y = s.index(mx)
            if mx > best[0] or (mx == best[0] and (y, c) < (best[1], best[2])):
                best = (mx, y, c)
    o += [("share_max_permille", best[0]), ("share_max_civ", best[2]), ("share_max_year", best[1])]
    for k in SHARE_LEVELS:
        longest = 0
        for c in sorted(d.shares):
            run = 0
            for x in d.shares[c]:
                run = run + 1 if x > k else 0
                longest = max(longest, run)
        o.append(("share_over_%d_years" % k, longest))
    rel = t["relation"]
    wars = [r for r in rel if r[4] == "war"]
    o += [("relations", len(rel)), ("relations_open", sum(1 for r in rel if r[6] is None)), ("wars", len(wars)),
          ("wars_open", sum(1 for r in wars if r[6] is None))]
    civ_race = {c[0]: c[2] for c in civs}
    for r in t["race"]:
        o.append(("population_" + r[1], sum(s[11] for s in stand if s[8] and civ_race[s[8]] == r[0])))
    for r in t["race"]:
        o.append(("settlements_standing_" + r[1], sum(1 for s in stand if s[8] and civ_race[s[8]] == r[0])))
    for r in t["race"]:
        o.append(("regions_held_" + r[1], sum(1 for x in held_open if civ_race[x[3]] == r[0])))
    alive = [c[0] for c in civs if c[8] is None]
    o.append(("civ_settlements_max", max([sum(1 for s in stand if s[8] == c) for c in alive] or [0])))
    kind_of = {e[0]: e[3] for e in t["event"]}
    o.append(("settlements_colonies", sum(1 for s in st if kind_of.get(s[7]) == K["colony_founded"])))
    o.append(("civilizations_seceded", sum(1 for c in civs if kind_of.get(c[7]) == K["civ_seceded"])))
    o += [("relations_enmity", sum(1 for r in rel if r[4] == "enmity")),
          ("relations_peace", sum(1 for r in rel if r[4] == "peace"))]
    wy = [(r[6] if r[6] is not None else E) - r[5] for r in wars]
    o += [("war_years_total", sum(wy)), ("war_years_max", max(wy or [0]))]
    o.append(("civilizations_conquered", sum(1 for c in civs if c[9] and kind_of[c[9]] == K["civ_conquered"])))
    o.append(("settlements_sacked", sum(1 for s in st if s[13] and kind_of[s[13]] == K["sacked"])))
