# Reading a world (sqlite3, read only). Text is decoded as Latin-1 so that every stored byte maps to one
# character and escaping works on bytes (6.1).
# ---------------------------------------------------------------------------

def _latin1(b):
    return b.decode("latin-1")


def connect(path):
    conn = sqlite3.connect("file:%s?mode=ro&immutable=1" % path, uri=True)
    conn.text_factory = _latin1
    return conn


def pk_rows(conn, table):
    info = conn.execute("SELECT name, pk FROM pragma_table_info(?) ORDER BY cid", (table,)).fetchall()
    cols = [r[0] for r in info]
    pks = [r[0] for r in sorted((r for r in info if r[1] > 0), key=lambda r: r[1])]
    order = ", ".join('"%s" COLLATE BINARY' % p for p in pks)
    return cols, conn.execute('SELECT %s FROM "%s" ORDER BY %s' % (", ".join('"%s"' % c for c in cols), table,
                                                                   order)).fetchall()


def load_world(path):
    conn = connect(path)
    try:
        meta = dict(conn.execute("SELECT key, value FROM meta").fetchall())
        t = {name: pk_rows(conn, name)[1] for name in TABLES_READ}
    finally:
        conn.close()
    return World(meta, t)


def enc_value(v):
    if v is None:
        return b"\x00"
    if isinstance(v, int):
        return b"\x01" + struct.pack("<q", v)
    b = v.encode("latin-1") if isinstance(v, str) else bytes(v)
    return b"\x03" + struct.pack("<Q", len(b)) + b


def table_hash(ncols, rows):
    data = bytearray(struct.pack("<Q", ncols))
    for row in rows:
        for v in row:
            data += enc_value(v)
    return hashlib.sha256(bytes(data)).hexdigest()


def detail_tables(path):
    """hash --detail's table lines (P0-04 8): one per table but sqlite_*, ascending name."""
    conn = connect(path)
    try:
        names = sorted((r[0] for r in conn.execute("SELECT name FROM sqlite_schema WHERE type = 'table'")
                        if not r[0].startswith("sqlite_")), key=lambda s: s.encode("latin-1"))
        out = []
        for name in names:
            cols, rows = pk_rows(conn, name)
            out.append((name, table_hash(len(cols), rows)))
        return out
    finally:
        conn.close()


