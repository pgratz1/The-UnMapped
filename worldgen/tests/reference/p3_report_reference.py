def ddl_statements():
    with open(SCHEMA_MD, encoding="utf-8") as f:
        text = f.read()
    block = text.split("## 1. DDL at version 7", 1)[1].split("```", 2)[1]
    return [s for s in block.splitlines() if s.startswith("CREATE TABLE")]


def write_fixture(name, out):
    meta, rows = expand_fixture(load_fixture(name))
    if os.path.exists(out):
        os.remove(out)
    conn = sqlite3.connect(out)
    try:
        for s in ddl_statements():
            conn.execute(s)
        for k in sorted(meta):
            conn.execute("INSERT INTO meta VALUES (?, ?)", (k, meta[k]))
        for table, rs in rows.items():
            for r in rs:
                conn.execute('INSERT INTO "%s" VALUES (%s)' % (table, ", ".join("?" * len(r))), r)
        conn.commit()
    finally:
        conn.close()


