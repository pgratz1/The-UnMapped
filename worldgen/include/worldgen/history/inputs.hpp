#pragma once

// The inputs of the history stage (spec P3-04 3.2, 3.3; audit advisory A2):
// exactly what the world file stores and the stage reads, from the
// pipeline's context or from a stored world (resume). The two constructors
// give equal values for the same world (H8), checked by test R1.

#include <cstdint>
#include <vector>

#include "worldgen/data/content.hpp"
#include "worldgen/db/layer_blob.hpp"
#include "worldgen/db/reader.hpp"
#include "worldgen/db/writer.hpp"
#include "worldgen/history/params.hpp"

namespace worldgen::stages {
class StageContext;
}

namespace worldgen::history {

// Adding a member: extend history_inputs_from, history_inputs_from_world,
// R1 (P3-04 16.3 item 19) and the field-count test R2 (item 20, structured
// bindings of exactly the current member count), which fails to compile
// until then.
struct HistoryInputs {
    std::uint64_t seed = 0;
    std::int64_t map_size = 0;
    HistoryParams params;
    std::vector<db::RegionRow> regions;              // id order
    std::vector<db::RegionBorderRow> region_borders; // (a, b) order
    std::vector<db::RegionBiomeRow> region_biomes;   // (region, biome) order
    std::vector<db::RaceRow> races;                  // id order
    std::vector<db::RaceBiomeRow> race_biomes;       // (race, biome) order
    std::vector<db::CultureRow> cultures;            // id order
    std::vector<db::GodRow> gods;                    // id order
    std::vector<db::AgeRow> ages;                    // id order
    db::LayerGrid region_layer;                      // layer `region`
    db::LayerGrid water_layer;                       // layer `water`
    std::vector<db::BiomeRow> biomes;                // id order (P3-05 3.2)
    db::LayerGrid habitability_layer;                // layer `habitability`
    db::LayerGrid river_layer;                       // layer `river`
    db::LayerGrid flow_dir_layer;                    // layer `flow_dir`

    friend bool operator==(const HistoryInputs&, const HistoryInputs&) = default;
};

// The rows, layers and settings of the stored world the stage reads, from
// the pipeline's context: StageContext::seed(), map_size(),
// history_params() and the committed rows and layers of earlier stages.
// FatalError (StageContext::layer) when layer `region`, `water`,
// `habitability`, `river` or `flow_dir` was not written by an earlier stage.
[[nodiscard]] HistoryInputs history_inputs_from(const stages::StageContext& context);

// The same from a world file (resume): meta parsed (history_params_from_meta),
// tables and layers read back. FatalError "history: resume: <reason>" when
// the world cannot be resumed, checked in this order: "schema version <v>,
// this build reads 7"; "the world's data content hash differs from the
// loaded data"; "the world was generated by <version>, this build is
// <GENERATOR_VERSION>"; "meta.stages is '<stages>', expected the stages up
// to chronology"; then "<table or layer>: <reason>" when a table or layer
// cannot be read.
[[nodiscard]] HistoryInputs history_inputs_from_world(const db::WorldReader& world, const data::ContentSet& content);

}  // namespace worldgen::history
